import fs from 'node:fs';
import path from 'node:path';
import { AskpassServer, ASKPASS_SCRIPT, askContext, type Ask, type AskContext, type Prompt } from '../addons/git/askpass';
import type { CommandPrompt } from '../shared/bash-mode';
import type { HostKind } from './host';
import type { Target } from './target';

/**
 * sudo's password for the "!" commands the user runs from a message box,
 * asked by Looper on the device that ran the command instead of in the
 * command's terminal. It's the Git addon's askpass (askpass.ts): sudo runs
 * SUDO_ASKPASS, a script that runs Looper's executable as Node with a small
 * client, which sends the prompt and the command's token to the server
 * (a Unix socket in a private folder, a named pipe on Windows) and prints
 * the answer. An answer stays in memory: none is stored or logged.
 *
 * A command is given a folder of its own on its PATH with a `sudo` that runs
 * the real one with -A, so a plain "sudo cmd" asks this way, and the agent's
 * own commands (whose PATH doesn't have the folder) keep asking nobody.
 */

/** The client SUDO_ASKPASS's script runs; the protocol of the Git addon's askpass-client.ts. */
export const ASKPASS_CLIENT = `// generated by looper: asks Looper for sudo's password (see src/engine/sudo-askpass.ts)
const { connect } = require('node:net');
const pipe = process.env.LOOPER_ASKPASS_PIPE;
const token = process.env.LOOPER_ASKPASS_TOKEN;
if (!pipe || !token) {
  process.stderr.write("askpass: this program asks for sudo's password in Looper, which didn't start it.\\n");
  process.exit(1);
}
let buf = '';
let answered = false;
process.exitCode = 1;
const sock = connect(pipe);
sock.setEncoding('utf8');
sock.on('connect', () => sock.write(JSON.stringify({ token, prompt: process.argv[2] || '' }) + '\\n'));
sock.on('data', (d) => {
  if (answered) return;
  buf += d;
  const nl = buf.indexOf('\\n');
  if (nl < 0) return;
  answered = true;
  let answer;
  try {
    answer = JSON.parse(buf.slice(0, nl)).answer;
  } catch {}
  sock.end();
  if (typeof answer === 'string') {
    process.stdout.write(answer + '\\n');
    process.exitCode = 0;
  }
});
sock.on('error', (e) => process.stderr.write('askpass: ' + e.message + '\\n'));
`;

/**
 * The `sudo` a command finds first: the real one (the next on PATH) with -A,
 * which takes the password from SUDO_ASKPASS. Left alone when the user gave
 * -S (the password on stdin), which -A can't be combined with. Only sudo's
 * own options are looked at, as its getopt reads them
 * ("+Aa:BbC:c:D:Eeg:Hh::iKklnPp:R:r:SsT:t:U:u:Vv"): they end at "--" or the
 * first word that isn't one, so the command's arguments (ls -lS) don't count,
 * and an option's value (-p "Say S") isn't read as options.
 */
export const SUDO_WRAPPER = `#!/bin/sh
# generated by looper: sudo asks for its password in Looper
d=$(cd "$(dirname "$0")" && pwd)
p=$(printf '%s' "$PATH" | tr ':' '\\n' | while IFS= read -r e; do [ "$e" = "$d" ] || printf '%s:' "$e"; done)
real=$(PATH="\${p%:}" command -v sudo) || { echo "sudo: command not found" >&2; exit 127; }
skip=
for a in "$@"; do
  if [ -n "$skip" ]; then skip=; continue; fi
  case "$a" in
    --) break ;;
    -S | --stdin) exec "$real" "$@" ;;
    --auth-type | --close-from | --chdir | --group | --host | --login-class | --prompt | --chroot | --role | --type | --command-timeout | --other-user | --user) skip=1 ;;
    --*) ;;
    -?*)
      o=\${a#-}
      while [ -n "$o" ]; do
        c=\${o%"\${o#?}"}
        o=\${o#?}
        case "$c" in
          S) exec "$real" "$@" ;;
          h) break ;;
          [aCcDgpRrTtUu]) [ -n "$o" ] || skip=1; break ;;
        esac
      done ;;
    *) break ;;
  esac
done
exec "$real" -A "$@"
`;

/** Where a command's folder with the wrapper and the askpass script goes, inside its run's folder. */
const BIN_DIR = 'sudo-bin';

/** What a prompt asks the user, in words. */
export function commandPrompt(p: Prompt, retry: boolean): Omit<CommandPrompt, 'id'> {
  if (p.kind === 'sudo') return { text: `Enter the password for ${p.user}`, secret: true, retry };
  const last = p.text.replace(/\r/g, '').trim().split('\n').pop()!.trim().replace(/:\s*$/, '');
  const secret = p.kind === 'other' ? p.secret : p.kind !== 'username' && p.kind !== 'hostKey' && p.kind !== 'confirm';
  return { text: last || 'Enter the answer', secret, retry };
}

/** Shows a prompt and resolves with the answer; null: the user cancelled, or the command ended. */
export type AskUser = (prompt: Prompt, retry: boolean) => Promise<string | null>;

/** What a command that may ask for sudo's password needs: the lines that set it up, and its end. */
export interface SudoSetup {
  /** Shell lines for the start of the command's launcher: the variables and the folder on PATH. */
  prologue: string;
  /** The command ended: its token stops working. */
  done: () => void;
}

export class SudoAskpass {
  private server?: AskpassServer;
  private clientFile = '';
  private readonly handlers = new WeakMap<AskContext, AskUser>();

  constructor(
    private readonly o: {
      host: HostKind;
      dataDir: string;
      /** Looper's executable; the process's own by default. */
      exe?: string;
      log?: (line: string) => void;
    },
  ) {}

  private readonly ask: Ask = async (prompt, { retry, ctx }) => {
    const answer = await this.handlers.get(ctx)?.(prompt, retry);
    return typeof answer === 'string' ? { answer } : 'cancelled';
  };

  private prompter(): AskpassServer {
    this.server ??= new AskpassServer({
      host: this.o.host,
      dataDir: path.join(this.o.dataDir, 'askpass'),
      exe: this.o.exe ?? process.execPath,
      client: this.clientFile,
      ask: this.ask,
      log: this.o.log,
    });
    return this.server;
  }

  /** Stop listening: the commands' tokens stop working. */
  close(): void {
    this.server?.close();
    this.server = undefined;
  }

  /** The client in the data dir, where a program on either side of WSL reads it. */
  private async writeClient(): Promise<void> {
    const dir = path.join(this.o.dataDir, 'askpass');
    this.clientFile = path.join(dir, 'sudo-askpass.js');
    const have = await fs.promises.readFile(this.clientFile, 'utf8').catch(() => null);
    if (have === ASKPASS_CLIENT) return;
    await fs.promises.mkdir(dir, { recursive: true });
    const tmp = `${this.clientFile}.${process.pid}.tmp`;
    await fs.promises.writeFile(tmp, ASKPASS_CLIENT);
    await fs.promises.rename(tmp, this.clientFile);
  }

  /**
   * Set up one command of a run in `runDir` on `target`: its token, its
   * folder with the wrapper and the script, and the lines that export them. `ask` shows
   * its prompts. Undefined when it can't be set up (a target without sudo,
   * or the server can't listen): the command then asks in its terminal.
   */
  async setup(target: Target, runDir: string, ask: AskUser): Promise<SudoSetup | undefined> {
    if (target.kind !== 'wsl') return undefined;
    await this.writeClient();
    const ctx = askContext();
    this.handlers.set(ctx, ask);
    const cmd = await this.prompter().command(ctx, 'wsl');
    if (!cmd) return undefined;
    const dir = path.join(runDir, BIN_DIR);
    await fs.promises.mkdir(dir, { recursive: true });
    const script = path.join(dir, 'askpass');
    await Promise.all([
      fs.promises.writeFile(path.join(dir, 'sudo'), SUDO_WRAPPER, { mode: 0o755 }),
      fs.promises.writeFile(script, `${ASKPASS_SCRIPT}\n`, { mode: 0o755 }),
    ]);
    // Across WSL the server's variables name Looper.exe, which the script runs from the distro by its path there.
    const cross = 'LOOPER_ASKPASS_EXE' in cmd.env;
    const { LOOPER_ASKPASS_PIPE: pipe, LOOPER_ASKPASS_TOKEN: token, LOOPER_ASKPASS_JS: js } = cmd.env;
    const exe = target.toTargetPath(cross ? cmd.env.LOOPER_ASKPASS_EXE : cmd.env.LOOPER_ASKPASS_BIN);
    const q = (s: string) => target.quote(s);
    const lines = [
      `export LOOPER_ASKPASS_PIPE=${q(pipe)} LOOPER_ASKPASS_TOKEN=${q(token)} LOOPER_ASKPASS_JS=${q(js)} LOOPER_ASKPASS_BIN=${q(exe)} SUDO_ASKPASS=${q(target.toTargetPath(script))}`,
      // Only the variables WSLENV names reach Looper.exe.
      ...(cross ? ['export WSLENV="${WSLENV:+$WSLENV:}LOOPER_ASKPASS_PIPE:LOOPER_ASKPASS_TOKEN"'] : []),
      `export PATH=${q(target.toTargetPath(dir))}":$PATH"`,
    ];
    return { prologue: lines.join('\n'), done: () => cmd.done(false) };
  }
}

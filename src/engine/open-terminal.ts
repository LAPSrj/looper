/** The hooks that record a terminal session's conversation, as target paths. */
export interface TerminalHooks {
  /** Claude: the settings file with the SessionStart and Stop hooks. */
  claudeSettings?: string;
  /** Codex: the notify hook's argv. */
  codexNotify?: string[];
}

/**
 * The harness command line as a run would build it — model, effort, permission
 * mode, harness args, extra args — minus the prompt and the run plumbing (system
 * prompt, headless flags): a plain interactive session for the user.
 * `resumeSessionId` reopens that conversation instead of starting a fresh one;
 * `hooks` record it, so the session can show in the Runs tab.
 */
export function terminalHarnessCommand(
  task: Task,
  target: Target,
  harness: Harness,
  resumeSessionId?: string,
  hooks: TerminalHooks = {},
): string {
  const q = (s: string) => target.quote(s);
  const a = task.agent;
  const effort = resolveEffort(a, harness);
  const parts: string[] = [a.command ?? harness.command];
  if (harness.kind === 'claude-code') {
    if (a.model) parts.push('--model', q(a.model));
    if (effort) parts.push('--effort', q(effort));
    if (a.permissionMode) parts.push('--permission-mode', q(a.permissionMode));
    if (resumeSessionId) parts.push('--resume', q(resumeSessionId));
    if (hooks.claudeSettings) parts.push('--settings', q(hooks.claudeSettings));
  } else if (harness.kind === 'codex') {
    for (const arg of codexPermissionArgs(a.permissionMode, true)) parts.push(arg);
    if (a.model) parts.push('--model', q(a.model));
    if (effort) parts.push('-c', q('model_reasoning_effort=' + effort));
    // TOML literal strings, as a run passes it: PowerShell would mangle a double quote.
    if (hooks.codexNotify) parts.push('-c', q(`notify=[${hooks.codexNotify.map((c) => `'${c}'`).join(',')}]`));
    if (resumeSessionId) parts.push('resume', q(resumeSessionId));
  }
  for (const arg of harness.args) parts.push(q(arg));
  for (const extra of a.extraArgs) parts.push(q(extra));
  return parts.join(' ');
}

/**
 * Launcher script for a terminal session: the run launcher's env + cd, without
 * the run-only plumbing. `prelude` runs just before the harness.
 */
export function renderTerminalScript(
  target: Target,
  task: Task,
  env: Record<string, string>,
  command: string,
  prelude?: string,
  /** Target path of a folder of helper commands, put in front of PATH. */
  binDir?: string,
): string {
  if (target.kind === 'windows') {
    const lines: string[] = [`# generated by looper — task ${task.id} terminal session`];
    for (const [k, v] of Object.entries(env)) lines.push(`$env:${k} = ${target.quote(v)}`);
    if (binDir) lines.push(`$env:PATH = ${target.quote(binDir)} + ';' + $env:PATH`);
    lines.push(`Set-Location -LiteralPath ${target.quote(task.cwd)}`);
    if (prelude) lines.push(prelude);
    lines.push(command);
    lines.push('');
    return lines.join('\r\n');
  }
  const lines: string[] = ['#!/usr/bin/env bash', `# generated by looper — task ${task.id} terminal session`];
  for (const [k, v] of Object.entries(env)) lines.push(`export ${k}=${target.quote(v)}`);
  if (binDir) lines.push(`export PATH=${target.quote(binDir)}":$PATH"`);
  lines.push(`cd ${target.quote(task.cwd)} || echo "looper: cannot cd to ${task.cwd}" >&2`);
  if (prelude) lines.push(prelude);
  // The sourcing shell is interactive, so a failing exec leaves it open with the error visible.
  lines.push('exec ' + command);
  lines.push('');
  return lines.join('\n');
}

export interface TerminalLaunch {
  command: string;
  args: string[];
  /** Windows host: the args are one pre-quoted cmd.exe line and must pass through verbatim. */
  verbatim?: boolean;
}

/** Quote one token of a cmd.exe `start` line. */
const winTok = (s: string) => (/[\s"']/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);

export interface TerminalLaunchOpts {
  /** Launcher path as the target sees it. */
  launcherTarget: string;
  /** Host path of the launcher (mac/linux emulators run it directly). */
  launcherHost: string;
  /** `source '<launcherTarget>'`, quoted for the target shell (bash targets). */
  sourceCmd: string;
  /** Bash targets: the environment's shell + flags. Default: bash -lic. */
  shell?: string;
  /** WSL environments on a Windows host: the distro name. */
  distro?: string;
}

/**
 * Ways to open the launcher in a terminal window, in preference order. On
 * Windows `cmd /c start` hands the session to the user's default terminal
 * (Windows Terminal when set as default); from WSL the same line runs through
 * interop. On Linux the common emulators are tried until one spawns.
 */
export function buildTerminalLaunches(
  host: HostKind,
  targetKind: Target['kind'],
  opts: TerminalLaunchOpts,
): TerminalLaunch[] {
  if (targetKind === 'windows') {
    const ps = ['powershell.exe', '-NoExit', '-NoLogo', '-ExecutionPolicy', 'Bypass', '-File', opts.launcherTarget];
    if (host === 'windows') {
      return [{ command: 'cmd.exe', args: ['/d', '/c', `start "" ${ps.map(winTok).join(' ')}`], verbatim: true }];
    }
    return [{ command: 'cmd.exe', args: ['/c', 'start', '', ...ps] }];
  }
  const shellParts = (opts.shell?.trim() || DEFAULT_SHELL).split(/\s+/);
  const inner = [...shellParts, opts.sourceCmd];
  if (host === 'windows') {
    const line = ['wsl.exe', ...(opts.distro ? ['-d', opts.distro] : []), '--', ...inner];
    return [{ command: 'cmd.exe', args: ['/d', '/c', `start "" ${line.map(winTok).join(' ')}`], verbatim: true }];
  }
  if (host === 'wsl') {
    const distro = wslDistroName();
    return [
      { command: 'cmd.exe', args: ['/c', 'start', '', 'wsl.exe', ...(distro ? ['-d', distro] : []), '--', ...inner] },
    ];
  }
  if (host === 'mac') return [{ command: 'open', args: ['-a', 'Terminal', opts.launcherHost] }];
  const emulators = process.env.TERMINAL
    ? [process.env.TERMINAL]
    : ['x-terminal-emulator', 'gnome-terminal', 'konsole', 'xfce4-terminal', 'xterm'];
  return emulators.map((cmd) =>
    cmd === 'gnome-terminal' ? { command: cmd, args: ['--', ...inner] } : { command: cmd, args: ['-e', ...inner] },
  );
}

function trySpawn(l: TerminalLaunch): Promise<boolean> {
  return new Promise((resolve) => {
    try {
      const child = spawn(l.command, l.args, {
        detached: true,
        stdio: 'ignore',
        ...(l.verbatim ? { windowsVerbatimArguments: true } : {}),
      });
      child.once('error', () => resolve(false));
      child.once('spawn', () => {
        child.unref();
        resolve(true);
      });
    } catch {
      resolve(false);
    }
  });
}

/** What makes a terminal session a Remote Control conversation (Claude Code only). */
export interface RemoteLaunch {
  /** The session's name in the Claude app's session list (`--remote-control <name>`). */
  name: string;
  /** Instructions appended to the system prompt. */
  systemPrompt?: string;
  /** Helper commands written into the session's bin folder, which goes in front of PATH. */
  helpers?: Record<string, string>;
  env?: Record<string, string>;
  /** More keys for the session's settings file, next to its hooks. */
  settings?: Record<string, unknown>;
  /** More arguments for the harness, already quoted for the target's shell. */
  args?: string[];
  /** Runs in the launcher just before the harness. */
  prelude?: string;
}

export interface OpenTerminalDeps {
  host: HostKind;
  settings: Settings;
  log: Logger;
}

/**
 * Write the launcher of a terminal session into `dir`: same environment,
 * working directory, model and arguments as a run, but interactive and
 * prompt-less. `resumeSessionId` continues that conversation (Continue in
 * Terminal). With `record` (a Looper terminal window, whose `dir` is its run
 * folder), Claude Code and Codex get the hooks a run uses to record the
 * conversation there: Claude's session.json and stop.json, Codex's notify
 * payload as stop.json and its home folder as codex-home. With `remote`
 * (Claude Code, recorded), the session is a Remote Control conversation: it
 * also records each message the user sends (prompt.json), so Looper can tell
 * an empty conversation from a used one and a running turn from an idle one.
 */
export function writeTerminalLauncher(
  task: Task,
  deps: Pick<OpenTerminalDeps, 'host' | 'settings'>,
  dir: string,
  resumeSessionId?: string,
  record = false,
  remote?: RemoteLaunch,
): { target: Target; launcherHost: string } {
  const env = resolveEnvironment(task, deps.settings);
  const harness = resolveHarness(task, env);
  const target = createTarget(task, { host: deps.host, settings: deps.settings });
  const t = (...parts: string[]) => target.toTargetPath(path.join(dir, ...parts));
  const hooks: TerminalHooks = {};
  let prelude: string | undefined;
  if (record && harness.kind === 'claude-code') {
    const pipe = (file: string) => [{ hooks: [{ type: 'command', command: target.renderPipeHook(t(file)) }] }];
    writeJsonAtomic(path.join(dir, 'settings.json'), {
      // A Remote Control session has nobody at the computer to answer the MCP servers dialog.
      ...projectMcpApproval(harness),
      ...remote?.settings,
      hooks: {
        SessionStart: pipe('session.json'),
        // Each finished turn: the session becomes a run with its first one.
        Stop: pipe('stop.json'),
        ...(remote ? { UserPromptSubmit: pipe('prompt.json') } : {}),
      },
    });
    hooks.claudeSettings = t('settings.json');
  } else if (record && harness.kind === 'codex') {
    writeText(path.join(dir, 'bin', target.notifyHookFile), target.renderNotifyHook(t('stop.json')), 0o755);
    hooks.codexNotify = target.notifyCommand(t('bin', target.notifyHookFile));
    prelude = recordCodexHome(target.kind, target.quote(t('codex-home')));
  }
  let command = terminalHarnessCommand(task, target, harness, resumeSessionId, hooks);
  if (remote && harness.kind === 'claude-code') {
    command += ` --remote-control ${target.quote(remote.name)}`;
    if (remote.systemPrompt) {
      writeText(path.join(dir, 'system.txt'), remote.systemPrompt);
      command += ` --append-system-prompt ${target.catFile(t('system.txt'))}`;
    }
    for (const arg of remote.args ?? []) command += ` ${arg}`;
  }
  if (remote?.prelude) prelude = prelude ? `${prelude}\n${remote.prelude}` : remote.prelude;
  const helpers = Object.entries(remote?.helpers ?? {});
  for (const [name, content] of helpers) writeText(path.join(dir, 'bin', name), content, 0o755);
  const launcherHost = path.join(dir, 'terminal' + target.launcherExt);
  const vars = { ...harness.env, ...task.env, ...remote?.env };
  writeText(launcherHost, renderTerminalScript(target, task, vars, command, prelude, helpers.length ? t('bin') : undefined), 0o755);
  return { target, launcherHost };
}

/**
 * Open the task's harness in a window of the system's own terminal (see
 * `writeTerminalLauncher`), its launcher in the task's data folder. Looper
 * has no hold on that window and can't tell when the session ends, so the
 * session isn't recorded as a run.
 */
export async function openTaskTerminal(task: Task, deps: OpenTerminalDeps, taskDir: string, resumeSessionId?: string): Promise<void> {
  const env = resolveEnvironment(task, deps.settings);
  const { target, launcherHost } = writeTerminalLauncher(task, deps, taskDir, resumeSessionId);
  const launcherTarget = target.toTargetPath(launcherHost);
  const launches = buildTerminalLaunches(deps.host, target.kind, {
    launcherTarget,
    launcherHost,
    sourceCmd: `source ${target.quote(launcherTarget)}`,
    shell: env.kind !== 'windows' ? env.shell : undefined,
    distro: env.kind === 'wsl' ? env.distro : undefined,
  });
  for (const l of launches) {
    if (await trySpawn(l)) {
      deps.log.info(`[${task.id}] opened terminal: ${l.command} ${l.args.join(' ')}`);
      return;
    }
  }
  throw new Error('Could not open a terminal window.');
}

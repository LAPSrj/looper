import fs from 'node:fs';
import path from 'node:path';
import { writeJsonAtomic, writeText } from './store/fsutil';

/**
 * Looper's mod for a Claude Code session: a hooks module Claude Code loads
 * from the run folder (`--plugin-dir`), the same JavaScript on every target.
 * It does inside Claude Code what Looper otherwise did from outside, through
 * the same files in the run folder:
 *
 * - Guidance, related events, the delegated agents' messages and Looper's
 *   notice (an interactive chat's messages, in a chat) reach the agent while a
 *   tool of its runs, as a message its next request reads, instead of a hook
 *   process for every tool call. With no turn running, they start one, as if
 *   typed, but never over a draft someone is typing in the terminal.
 * - Stop ends the running turn ($.turn.abort) instead of an Esc typed in.
 * - Each turn's start and end, its final answer and the session's usage (the
 *   context, the cost, the rate limits and when they reset) go to files the
 *   engine reads instead of the terminal's screen or the transcript.
 * - A subagent can't run the step's signal helpers, and a headless session
 *   can't schedule a CronCreate job that would never fire.
 * - An interactive session's mod hands each row of the main conversation, and
 *   the notes beside them a conversation shows, to the live folder as they
 *   are made, as the transcript records them. Interactive Claude Code writes
 *   its transcript seconds later, and holds some rows back until a tool call
 *   that waits ends, so chats and runs show the rows from there (LiveRows).
 *
 * The mod writes `mod.json` when it loads; a session that started without it
 * (`--bare`, a managed setting that allows no such mod) is ended by the engine.
 */

/** The run-folder name (after the step's prefix) of the mod's folder. */
export const MOD_DIR = 'looper-mod';

/** Files the mod writes and reads, by their run-folder names (after the step's prefix). */
export const MOD_FILES = {
  /** Written once the mod has loaded: its version and the session's id. */
  ready: 'mod.json',
  /** What the engine asks of the mod: `{ abort: n }`, each new n ending the running turn. */
  control: 'mod-control.json',
  /** Each main-agent turn's end: its answer, whether it was stopped, and why it ended. */
  turnEnd: 'turn-end.json',
  /** `$.session.usage()` as of the last turn or measure. */
  usage: 'usage.json',
  /** The last tool call's end: `{ at, tool, key }` (toolKey). */
  toolEnd: 'tool-end.json',
  /** The rows of the main conversation as they are made, one transcript record a file, named `<the mod's start>-<n>.json` to sort in order. */
  live: 'live',
} as const;

/** What tells one call of a tool from another, as the mod's toolKey reads it: its command, file, URL or pattern. */
export function toolKey(input: unknown): string {
  const rec = (input ?? {}) as Record<string, unknown>;
  for (const name of ['command', 'file_path', 'notebook_path', 'url', 'pattern']) {
    if (typeof rec[name] === 'string') return rec[name] as string;
  }
  return '';
}

/** What the generated mod needs, as target-native paths. */
export interface ModConfig {
  /**
   * Written by the mod (see MOD_FILES); `turn` is the file the engine's idle
   * clock watches, and `toolEnd` (set while Looper relays permission requests)
   * gets each tool call's end.
   */
  files: { ready: string; control: string; turnEnd: string; usage: string; turn: string; toolEnd?: string };
  /** Messages waiting for the agent, taken in this order (engine/guidance.ts), or none for a step that takes no guidance. */
  inbox: string[];
  /**
   * The inbox files whose messages are the user's own words. One waiting ends the running turn at a moment no tool
   * call is working and starts the next turn with it, as the user's prompt; the others go along as the mod's notes.
   */
  userInbox: string[];
  /** Helpers a subagent may not run, and what it is told. */
  signalCommands: string[];
  guardMessage: string;
  /** A helper that waits for the user (looper-ask): its Bash call gets this timeout. */
  ask?: { command: string; timeoutMs: number };
  /** Headless: CronCreate is refused with this reason. */
  cronRefusal?: string;
  headless: boolean;
  /** The session started with a prompt of its own: messages wait for its first turn to end. */
  prompted: boolean;
  windows: boolean;
  /** The folder the mod hands each row of the main conversation to (MOD_FILES.live), or none. */
  live?: string;
}

/** The mod's version, in mod.json and plugin.json: a run folder's mod is rewritten whenever a session starts. */
export const MOD_VERSION = '1.1.0';

/** The hooks module. `__CONFIG__` becomes the session's ModConfig. */
const MOD_SOURCE = String.raw`// Generated by Looper for one Claude Code session: see src/engine/claude-mod.ts.
const CONFIG = __CONFIG__

let turnId = null
let turns = 0
let toolsInFlight = 0
// The main turn's model request is streaming, and the steps it has made.
let streaming = false
let stepsDone = 0
// The main turn's tool calls by tool_use id, from their request until their result row is stored.
const pendingCalls = new Map()
let interrupting = false
let polling = false
let lastAbort = 0
let usageAt = 0

// The live folder's rows (CONFIG.live), in the order they're made: every user and assistant row of the main
// conversation, and the notes beside them a conversation shows, each as the transcript will record it.
const LIVE_NOTES = ['queued_command', 'hook_additional_context', 'skill_listing', 'poll_events']
const liveStamp = String(Date.now())
let liveSeq = 0
let liveWrites = Promise.resolve()
// The blocks of one response share a message id, as the transcript's do.
let liveStep = 0
let lastDoor = null
// Each main-thread tool call's record by its tool_use id, until its result row takes it.
const toolRecords = new Map()
// The engine's stand-in reply, and the rows after it, until the turn's end says whether an API error ended the turn.
let held = null
// Prompts typed while a turn ran, as typed, until their delivery into the turn is handed over.
let typedMidTurn = []

// Each file is written after the one before it, so a row appears only once the rows before it are whole.
function writeLive($, record) {
  if (held && record !== held.reply) {
    held.after.push(record)
    return
  }
  // The row's id ends the name: the session step deletes the file once the transcript has the row.
  const name = CONFIG.live + (CONFIG.windows ? '\\' : '/') + liveStamp + '-' + String(++liveSeq).padStart(9, '0') + (record.uuid ? '-' + record.uuid : '') + '.json'
  const text = JSON.stringify(record)
  liveWrites = liveWrites.then(() => $.fs.write(name, text)).catch(() => {})
}

function releaseHeld($, apiError) {
  if (!held) return
  const { reply, after } = held
  held = null
  if (apiError) reply.isApiErrorMessage = true
  writeLive($, reply)
  for (const record of after) writeLive($, record)
}

function textOf(content) {
  return content.filter((b) => b && b.type === 'text').map((b) => b.text).join('\n')
}

// A row of the main conversation as the transcript will record it.
function liveRow($, e, stored) {
  const door = e.door
  if (door === 'response' && lastDoor !== 'response') liveStep += 1
  lastDoor = door
  const m = stored.message
  const content = Array.isArray(m.content) ? m.content : []
  const origin = e.origin || {}
  const base = { uuid: stored.uuid, timestamp: new Date().toISOString(), isSidechain: false }
  if (m.type === 'attachment') {
    if (!LIVE_NOTES.includes(m.name)) return
    // The note as the model reads it, which holds what a conversation reads of it.
    const text = textOf(content)
    const notice = origin.kind === 'task-notification' || text.includes('<task-notification>')
    // A prompt typed mid-turn reaches the model wrapped in Claude Code's words: the transcript keeps it as typed.
    const typed = m.name === 'queued_command' && !notice ? typedMidTurn.findIndex((t) => text.includes(t)) : -1
    const attachment =
      m.name === 'queued_command'
        ? { type: m.name, prompt: typed >= 0 ? typedMidTurn.splice(typed, 1)[0] : text, commandMode: notice ? 'task-notification' : 'prompt' }
        : m.name === 'hook_additional_context'
          ? { type: m.name, hookEvent: origin.event, content: [text] }
          : m.name === 'skill_listing'
            ? { type: m.name, content: text }
            : { type: m.name }
    writeLive($, { type: 'attachment', ...base, attachment, rendered: [{ content: text }] })
    return
  }
  // A plugin's note is stored as an attachment (poll writes this one's), and a queued message isn't stored; the engine's notes (a Stop hook's feedback) are rows.
  if ((m.type !== 'user' && m.type !== 'assistant') || (door === 'note' && origin.kind !== 'engine') || door === 'queue') return
  // The turn goes on past a stand-in reply: it wasn't the error that ended the turn.
  releaseHeld($, false)
  const model = origin.kind === 'model' ? origin.model : undefined
  const record = { type: m.type, ...base, message: { role: m.role || m.type, content } }
  if (m.isMeta) record.isMeta = true
  if (m.type === 'assistant') {
    record.message.id = 'live-' + liveStamp + '-' + liveStep
    if (model) record.message.model = model
  }
  const result = content.find((b) => b && b.type === 'tool_result')
  if (result && toolRecords.has(result.tool_use_id)) {
    record.toolUseResult = toolRecords.get(result.tool_use_id)
    toolRecords.delete(result.tool_use_id)
  }
  if (m.type === 'assistant' && typeof model === 'string' && model.startsWith('<') && content.length > 0 && content.every((b) => b && b.type === 'text')) {
    held = { reply: record, after: [] }
    return
  }
  writeLive($, record)
}

async function writeJson($, file, value) {
  try {
    await $.fs.write(file, JSON.stringify(value))
  } catch {}
}

async function readJson($, file) {
  try {
    return JSON.parse(await $.fs.read(file))
  } catch {
    return null
  }
}

// Takes a waiting message: the move is the claim, so a hook taking the same file can't deliver it twice.
async function claim($, file) {
  if (!(await $.fs.exists(file))) return null
  const dest = file.replace(/\.json$/, '') + '-' + Date.now() + '-mod.json'
  const quoted = (p) => "'" + p.replace(/'/g, "''") + "'"
  const argv = CONFIG.windows
    ? ['powershell.exe', '-NoProfile', '-NonInteractive', '-Command', 'Move-Item -LiteralPath ' + quoted(file) + ' -Destination ' + quoted(dest) + ' -ErrorAction Stop']
    : ['mv', file, dest]
  try {
    const r = await $.process.run(argv, { timeoutMs: 15000 })
    if (r.exitCode !== 0) return null
  } catch {
    return null
  }
  const text = await readJson($, dest)
  return typeof text === 'string' && text ? text : null
}

async function takeMessage($, files = CONFIG.inbox) {
  for (const file of files) {
    const text = await claim($, file)
    if (text) return text
  }
  return null
}

async function anyWaiting($) {
  for (const file of CONFIG.inbox) if (await $.fs.exists(file)) return true
  return false
}

async function saveUsage($) {
  usageAt = Date.now()
  try {
    await writeJson($, CONFIG.files.usage, { at: Date.now(), ...(await $.session.usage()) })
  } catch {}
}

async function poll($) {
  // The context grows within a turn: the engine's context watch reads it every few seconds.
  if (turnId && Date.now() - usageAt > 5000) await saveUsage($)
  const control = await readJson($, CONFIG.files.control)
  if (control && typeof control.abort === 'number' && control.abort > lastAbort) {
    lastAbort = control.abort
    if (turnId) {
      try {
        await $.turn.abort({ turnId })
      } catch {}
    }
  }
  if (!CONFIG.inbox.length || !(await anyWaiting($))) return
  if (turnId) {
    // Nothing works but a Poll waiting: the user's message ends the turn now.
    if (!streaming && stepsDone > 0 && [...pendingCalls.values()].every((name) => name === 'Poll') && (await interrupt($, turnId))) return
    // A tool is running: the turn makes another request, which reads Looper's own messages.
    if (toolsInFlight === 0 && pendingCalls.size === 0) return
    const text = await takeMessage($, CONFIG.inbox.filter((f) => !CONFIG.userInbox.includes(f)))
    if (!text) return
    const note = await $.session.append({ message: { type: 'user', content: [{ type: 'text', text }] } })
    // The transcript keeps it as the plugin's note, under the id the append answers.
    if (CONFIG.live && note && note.uuid) {
      writeLive($, { type: 'attachment', uuid: note.uuid, timestamp: new Date().toISOString(), isSidechain: false, attachment: { type: 'plugin_note', plugin: 'looper', content: [text] } })
    }
    return
  }
  // Idle: the message starts the next turn, unless the session's own prompt hasn't run yet or someone is typing.
  if (CONFIG.headless || (CONFIG.prompted && turns === 0)) return
  const box = await $.prompt.read()
  if (box.text) return
  const text = await takeMessage($)
  if (text) await $.prompt.submit({ text, asUser: true })
}

// The user's message ends the turn id and starts the next one as their prompt: a note in the turn would never read as
// their words. Claude Code tells the agent a call it stopped (a Poll) ended to deliver the message that follows.
async function interrupt($, id) {
  if (interrupting) return false
  interrupting = true
  try {
    let text = null
    let from = null
    for (const file of CONFIG.userInbox) {
      text = await claim($, file)
      if (text) {
        from = file
        break
      }
    }
    if (!text) return false
    try {
      await $.turn.abort({ turnId: id })
    } catch {
      // The turn ended on its own meanwhile: the prompt starts the next one all the same.
    }
    // It runs once the session is idle, which the abort makes it.
    $.prompt.submit({ text, asUser: true }).catch(() => writeJson($, from, text))
    return true
  } finally {
    interrupting = false
  }
}

function commandOf(e) {
  return typeof e.command === 'string' ? e.command : ''
}

// What tells one call of a tool from another: the same key the engine reads off a permission request (toolKey in claude-mod.ts).
function toolKey(input) {
  for (const name of ['command', 'file_path', 'notebook_path', 'url', 'pattern']) {
    if (typeof input[name] === 'string') return input[name]
  }
  return ''
}

export function register(on) {
  on('session.start', async ($, e, next) => {
    const control = await readJson($, CONFIG.files.control)
    if (control && typeof control.abort === 'number') lastAbort = control.abort
    await writeJson($, CONFIG.files.ready, { version: '__VERSION__', sessionId: await $.session.id(), at: Date.now() })
    $.clock.every(500, async () => {
      if (polling) return
      polling = true
      try {
        await poll($)
      } catch {
      } finally {
        polling = false
      }
    })
    return next(e)
  })

  on('turn.start', async ($, e, next) => {
    if (e.agentId === undefined || e.agentId === null) {
      turnId = e.turnId
      stepsDone = 0
      streaming = false
      pendingCalls.clear()
      await writeJson($, CONFIG.files.turn, { at: Date.now() })
    }
    return next(e)
  })

  on('turn.complete', async ($, e, next) => {
    if (e.agentId === undefined || e.agentId === null) {
      turnId = null
      turns += 1
      streaming = false
      pendingCalls.clear()
      toolRecords.clear()
      typedMidTurn = []
      releaseHeld($, e.reason === 'error')
      await writeJson($, CONFIG.files.turnEnd, { at: Date.now(), answer: e.answer ?? '', aborted: e.isAborted === true, reason: e.reason ?? null })
      await saveUsage($)
    }
    return next(e)
  })

  on('turn.step', async function* ($, e, next) {
    if (e.agentId !== undefined && e.agentId !== null) return yield* next(e)
    pendingCalls.clear()
    // Between two requests no tool call runs: the user's message ends the turn here, before the next one.
    if (e.index > 0 && (await interrupt($, e.turnId))) return { turnId: e.turnId, index: e.index, answer: '', toolUses: [], stopReason: null, usage: null }
    streaming = true
    try {
      return yield* next(e)
    } finally {
      streaming = false
      stepsDone += 1
    }
  })

  on('session.append', async ($, e, next) => {
    const stored = await next(e)
    if ((e.agentId === undefined || e.agentId === null) && stored && stored.message && Array.isArray(stored.message.content)) {
      for (const b of stored.message.content) {
        if (!b) continue
        if (e.door === 'response' && b.type === 'tool_use' && typeof b.id === 'string') pendingCalls.set(b.id, b.name)
        if (e.door === 'tool-result' && b.type === 'tool_result') pendingCalls.delete(b.tool_use_id)
      }
    }
    if (CONFIG.live && (e.agentId === undefined || e.agentId === null) && stored && stored.message && stored.uuid) liveRow($, e, stored)
    return stored
  })

  on('prompt.submit', async ($, e, next) => {
    const r = await next(e)
    if (CONFIG.live && e.turnId && !e.command && r && typeof r.text === 'string' && r.text.trim()) typedMidTurn.push(r.text)
    return r
  })

  on('session.measure', async ($, e, next) => {
    await saveUsage($)
    return next(e)
  })

  on('tool.call', async ($, e, next) => {
    const main = e.agentId === undefined || e.agentId === null
    const command = commandOf(e)
    if (!main && command && CONFIG.signalCommands.some((c) => command.includes(c))) return { deny: CONFIG.guardMessage }
    if (CONFIG.cronRefusal && e.tool === 'CronCreate') return { deny: CONFIG.cronRefusal }
    const input = CONFIG.ask && command && new RegExp('(^|[\\s;&|(])' + CONFIG.ask.command + '(\\s|$)').test(command)
      ? { ...e, timeout: CONFIG.ask.timeoutMs }
      : e
    if (main) toolsInFlight += 1
    try {
      const r = await next(input)
      if (CONFIG.live && main && r && !r.deny && r.result !== undefined && typeof e.tool_use_id === 'string') toolRecords.set(e.tool_use_id, r.result)
      return r
    } finally {
      if (main) toolsInFlight -= 1
      // A call that waited for permission is settled: answered in the terminal, Looper's card goes.
      if (CONFIG.files.toolEnd) await writeJson($, CONFIG.files.toolEnd, { at: Date.now(), tool: e.tool, key: toolKey(e) })
    }
  })
}
`;

/** The mod's source for one session. */
export function renderMod(config: ModConfig): string {
  return MOD_SOURCE.replace('__CONFIG__', JSON.stringify(config, null, 2)).replace('__VERSION__', MOD_VERSION);
}

/** Write the mod into `hostDir` (its folder in the run folder), replacing what an earlier session left. */
export function writeClaudeMod(hostDir: string, config: ModConfig): void {
  fs.rmSync(hostDir, { recursive: true, force: true });
  writeJsonAtomic(path.join(hostDir, '.claude-plugin', 'plugin.json'), {
    name: 'looper',
    version: MOD_VERSION,
    description: "Looper's connection to this session: messages for the agent, Stop, and the turn's state.",
  });
  writeJsonAtomic(path.join(hostDir, 'hooks', 'hooks.json'), { modules: ['./register.js'] });
  writeText(path.join(hostDir, 'hooks', 'register.js'), renderMod(config));
}


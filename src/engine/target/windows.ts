/**
 * PowerShell test that a hook payload ($payload) comes from a subagent: claude
 * sends agent_id only on a subagent's call, and before tool_input, so the
 * command or a tool's output can't supply it.
 */
const SUBAGENT_TEST = `($payload -split '"tool_input"', 2)[0] -match '"agent_id"\\s*:'`;

/** PowerShell test that a helper runs under another session than the one its run started (a nested claude). */
const NESTED_TEST =
  `($env:${SESSION_SOCKET_VAR} -and $env:${SOCKET_FILE_VAR} -and (Test-Path -LiteralPath $env:${SOCKET_FILE_VAR}) -and ` +
  `([IO.File]::ReadAllText($env:${SOCKET_FILE_VAR}) -ne '') -and ([IO.File]::ReadAllText($env:${SOCKET_FILE_VAR}) -ne $env:${SESSION_SOCKET_VAR}))`;

/** A .cmd helper's first lines: --help or -h jumps to HELP_CMD_END, which prints its usage and signals nothing. */
const HELP_CMD = ['if /i "%~1"=="--help" goto looper_usage', 'if /i "%~1"=="-h" goto looper_usage'];

/** A .cmd helper's last lines: the end of its normal path, then the usage HELP_CMD jumps to. */
const HELP_CMD_END = (args: string): string[] => ['exit /b 0', ':looper_usage', `echo usage: %~n0 ${cmdEchoText(args)}`, 'exit /b 0'];

/** Text for a .cmd echo, with the characters cmd reads as operators escaped outside double quotes. */
function cmdEchoText(s: string): string {
  let quoted = false;
  return [...s]
    .map((c) => {
      if (c === '"') quoted = !quoted;
      return !quoted && '^&|<>'.includes(c) ? '^' + c : c;
    })
    .join('');
}

/** A .cmd helper's first lines: run by another session than its run's own, it refuses (see NESTED_TEST). */
const NESTED_CMD = [
  `if not defined ${SESSION_SOCKET_VAR} goto looper_owned`,
  `if not defined ${SOCKET_FILE_VAR} goto looper_owned`,
  `if not exist "%${SOCKET_FILE_VAR}%" goto looper_owned`,
  `for %%A in ("%${SOCKET_FILE_VAR}%") do if %%~zA==0 goto looper_owned`,
  `set /p "looper_sock="<"%${SOCKET_FILE_VAR}%"`,
  `if not "%looper_sock%"=="%${SESSION_SOCKET_VAR}%" (echo ${NESTED_REFUSAL}1>&2& exit /b 1)`,
  ':looper_owned',
];

export class WindowsTarget implements Target {
  readonly kind = 'windows' as const;
  readonly launcherExt = '.ps1';

  doneHelperFile(command: string): string {
    return command + '.cmd';
  }
  private readonly mountPrefix: string;

  constructor(
    private readonly ctx: TargetContext,
    mountPrefix?: string,
  ) {
    this.mountPrefix = mountPrefix?.trim() || '/mnt';
  }

  toTargetPath(hostPath: string): string {
    return translatePath(hostPath, {
      host: this.ctx.host,
      targetKind: 'windows',
      wslMountPrefix: this.mountPrefix,
      hostDistro: wslDistroName(),
    });
  }

  toHostPath(targetPath: string): string {
    return translateToHost(targetPath, {
      host: this.ctx.host,
      targetKind: 'windows',
      wslMountPrefix: this.mountPrefix,
    });
  }

  quote(s: string): string {
    return `'${s.replace(/'/g, "''")}'`;
  }

  catFile(targetPath: string): string {
    // Windows PowerShell 5.1 passes embedded double quotes to native commands
    // unescaped, splitting the argument; pre-escaping them keeps the file's
    // content one argument (verified against node/codex argv).
    return `((Get-Content -Raw -LiteralPath ${this.quote(targetPath)}) -replace '"','\\"')`;
  }

  envRef(name: string): string {
    return `$env:${name}`;
  }

  renderLauncher(spec: LauncherSpec): string {
    const lines: string[] = [`# generated by looper — task ${spec.taskId} run ${spec.runId}`];
    for (const [k, v] of Object.entries(spec.env)) {
      lines.push(`$env:${k} = ${this.quote(v)}`);
    }
    lines.push(`$env:PATH = ${this.quote(spec.binDir)} + ';' + $env:PATH`);
    if (spec.doneCommand) {
      const doneStatuses = spec.doneStatuses ?? [];
      const statuses = doneStatuses.map((s) => `'${s}'`).join(',');
      lines.push(
        `function ${spec.doneCommand} { param([Parameter(ValueFromRemainingArguments=$true)][string[]]$msg)`,
        `  if ($msg -and @('--help','-h') -contains $msg[0]) { Write-Output ${this.quote(`usage: ${spec.doneCommand} ${doneUsage(doneStatuses)}`)}; $global:LASTEXITCODE = 0; return }`,
        `  if (${NESTED_TEST}) { [Console]::Error.WriteLine(${this.quote(NESTED_REFUSAL)}); $global:LASTEXITCODE = 1; return }`,
        `  if ($env:${DELEGATE_BUSY_VAR} -and (Test-Path -LiteralPath $env:${DELEGATE_BUSY_VAR})) { [Console]::Error.Write([IO.File]::ReadAllText($env:${DELEGATE_BUSY_VAR})); $global:LASTEXITCODE = 1; return }`,
        "  $status = ''",
        `  if ($msg -and @(${statuses}) -contains $msg[0]) {`,
        '    $status = $msg[0]',
        '    $msg = if ($msg.Count -gt 1) { $msg[1..($msg.Count - 1)] } else { @() }',
        '  }',
        "  $text = if ($msg) { $msg -join ' ' } else { 'done' }",
        '  Set-Content -LiteralPath $env:LOOPER_DONE_FILE -Value ($status + [Environment]::NewLine + $text)',
        '}',
      );
    }
    lines.push(`Set-Location -LiteralPath ${this.quote(spec.cwd)}`);
    lines.push(`if (-not $?) { Write-Error "looper: cannot cd to ${spec.cwd}"; exit 97 }`);
    lines.push(spec.body);
    lines.push('exit $LASTEXITCODE');
    lines.push('');
    return lines.join('\r\n');
  }

  renderDoneHelper(statuses: readonly string[]): string {
    return [
      '@echo off',
      'setlocal',
      ...HELP_CMD,
      ...NESTED_CMD,
      `if defined ${DELEGATE_BUSY_VAR} if exist "%${DELEGATE_BUSY_VAR}%" (type "%${DELEGATE_BUSY_VAR}%" 1>&2 & exit /b 1)`,
      'set "status="',
      'set "msg=%*"',
      ...statuses.map((s) => `if /i "%~1"=="${s}" goto strip`),
      'goto write',
      ':strip',
      'set "status=%~1"',
      'set "msg="',
      ':collect',
      'shift',
      'if "%~1"=="" goto write',
      'if defined msg (set "msg=%msg% %~1") else (set "msg=%~1")',
      'goto collect',
      ':write',
      'if not defined msg set "msg=done"',
      'echo.%status%> "%LOOPER_DONE_FILE%"',
      'echo.%msg%>> "%LOOPER_DONE_FILE%"',
      ...HELP_CMD_END(doneUsage(statuses)),
      '',
    ].join('\r\n');
  }

  renderCodexHomeWrapper(command: string, codexHome: string): string {
    return [
      "$looperRealHome = if ($env:CODEX_HOME) { $env:CODEX_HOME } else { Join-Path $env:USERPROFILE '.codex' }",
      `$looperCodexHome = ${this.quote(codexHome)}`,
      'New-Item -ItemType Directory -Force -Path $looperCodexHome | Out-Null',
      "$looperAuth = Join-Path $looperCodexHome 'auth.json'",
      "$looperBase = Join-Path $looperCodexHome '.auth-base'",
      "$looperRealAuth = Join-Path $looperRealHome 'auth.json'",
      'if (-not (Test-Path -LiteralPath $looperAuth) -and (Test-Path -LiteralPath $looperRealAuth)) {',
      '  Copy-Item -LiteralPath $looperRealAuth -Destination $looperAuth',
      '  Copy-Item -LiteralPath $looperRealAuth -Destination $looperBase',
      '}',
      '$looperPrevHome = $env:CODEX_HOME',
      '$env:CODEX_HOME = $looperCodexHome',
      command,
      '$looperCode = $LASTEXITCODE',
      '$env:CODEX_HOME = $looperPrevHome',
      'if ((Test-Path -LiteralPath $looperAuth) -and (Test-Path -LiteralPath $looperBase) -and ((Get-FileHash -LiteralPath $looperAuth).Hash -ne (Get-FileHash -LiteralPath $looperBase).Hash)) {',
      '  if ((Test-Path -LiteralPath $looperRealAuth) -and ((Get-FileHash -LiteralPath $looperRealAuth).Hash -eq (Get-FileHash -LiteralPath $looperBase).Hash)) {',
      '    Copy-Item -LiteralPath $looperAuth -Destination "$looperRealAuth.looper" -Force',
      '    Move-Item -LiteralPath "$looperRealAuth.looper" -Destination $looperRealAuth -Force',
      '  }',
      '  Copy-Item -LiteralPath $looperAuth -Destination $looperBase -Force',
      '}',
      'exit $looperCode',
    ].join('\r\n');
  }

  renderRequestHelpers(ops: Record<string, string>, opts: RequestHelperOpts): Record<string, string> {
    // One PowerShell script does the request round trip; each command is a .cmd
    // shim (what PATH lookup finds from cmd, PowerShell and claude's shell alike).
    const out: Record<string, string> = {
      [`${opts.script}.ps1`]: [
        '# generated by looper — request helper',
        `if (${NESTED_TEST}) { [Console]::Error.WriteLine(${this.quote(NESTED_REFUSAL)}); exit 1 }`,
        '$op = $args[0]',
        '$rest = @($args | Select-Object -Skip 1)',
        `$d = $env:${opts.dirVar}`,
        "$rid = '{0}-{1}-{2}' -f [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds(), $PID, (Get-Random)",
        "$req = Join-Path $d 'requests'",
        "$res = Join-Path $d 'responses'",
        'New-Item -ItemType Directory -Force -Path $req, $res | Out-Null',
        '$tmp = Join-Path $req "$rid.tmp"',
        // The op, the caller's folder (for relative paths), then one line per argument.
        '[IO.File]::WriteAllLines($tmp, [string[]](@($op, (Get-Location).Path) + $rest))',
        'Move-Item -LiteralPath $tmp -Destination (Join-Path $req "$rid.req")',
        '$codeFile = Join-Path $res "$rid.code"',
        '$outFile = Join-Path $res "$rid.out"',
        `for ($i = 0; $i -lt ${requestPolls(opts)}; $i++) {`,
        '  if (Test-Path -LiteralPath $codeFile) {',
        '    if (Test-Path -LiteralPath $outFile) { [Console]::Out.Write([IO.File]::ReadAllText($outFile)) }',
        '    $code = [int]([IO.File]::ReadAllText($codeFile).Trim())',
        '    Remove-Item -LiteralPath $outFile, $codeFile -ErrorAction SilentlyContinue',
        '    exit $code',
        '  }',
        '  Start-Sleep -Milliseconds 500',
        '}',
        `[Console]::Error.WriteLine(${this.quote(`looper: no answer from Looper (${opts.hint})`)})`,
        'exit 1',
        '',
      ].join('\r\n'),
    };
    for (const [command, op] of Object.entries(ops)) {
      out[command + '.cmd'] = [
        '@echo off',
        `powershell.exe -NoLogo -NoProfile -ExecutionPolicy Bypass -File "%~dp0${opts.script}.ps1" ${op} %*`,
        'exit /b %ERRORLEVEL%',
        '',
      ].join('\r\n');
    }
    return out;
  }

  renderCliHelper(paths: { script: string; home: string; exe: string }): Record<string, string> {
    // Looper running in WSL has no Windows executable to give it.
    if (this.ctx.host !== 'windows') return {};
    const cmd = (p: string) => p.replace(/%/g, '%%');
    return {
      'looper.cmd': [
        '@echo off',
        'setlocal',
        `if not exist "${cmd(paths.script)}" (echo looper: Looper hasn't set up its command-line tool yet; try again in a minute 1>&2 & exit /b 1)`,
        'set "ELECTRON_RUN_AS_NODE=1"',
        `set "LOOPER_HOME=${cmd(paths.home)}"`,
        `"${cmd(paths.exe)}" "${cmd(paths.script)}" %*`,
        'exit /b %ERRORLEVEL%',
        '',
      ].join('\r\n'),
    };
  }

  renderTextHelper(envVar: string, fallback: string): string {
    return [
      '@echo off',
      'setlocal',
      ...HELP_CMD,
      ...NESTED_CMD,
      'set "msg=%*"',
      `if not defined msg set "msg=${fallback}"`,
      `echo.%msg%> "%${envVar}%"`,
      ...HELP_CMD_END(REASON_USAGE),
      '',
    ].join('\r\n');
  }

  renderStatusHelper(status: string, fallback: string): string {
    return [
      '@echo off',
      'setlocal',
      ...HELP_CMD,
      ...NESTED_CMD,
      'set "msg=%*"',
      `if not defined msg set "msg=${fallback}"`,
      `echo.${status}> "%LOOPER_DONE_FILE%"`,
      'echo.%msg%>> "%LOOPER_DONE_FILE%"',
      ...HELP_CMD_END(REASON_USAGE),
      '',
    ].join('\r\n');
  }

  renderPipeHook(targetPath: string): string {
    // Works whether claude runs hooks through cmd or a bash-like shell on Windows.
    // .NET writes UTF-8 without BOM; the console input is declared UTF-8 so the payload survives.
    const p = targetPath.replace(/\\/g, '/');
    return (
      'powershell -NoProfile -Command "[Console]::InputEncoding=[Text.Encoding]::UTF8; ' +
      `[IO.File]::WriteAllText('${p}', [Console]::In.ReadToEnd())"`
    );
  }

  renderSessionStartHook(sessionJson: string, socketFile: string): string {
    // No "$" anywhere: a bash-like shell would expand it inside the double quotes.
    const p = sessionJson.replace(/\\/g, '/');
    const s = socketFile.replace(/\\/g, '/');
    return (
      'powershell -NoProfile -Command "[Console]::InputEncoding=[Text.Encoding]::UTF8; ' +
      `[IO.File]::WriteAllText('${p}', [Console]::In.ReadToEnd()); ` +
      `[IO.File]::WriteAllText('${s}', [string][Environment]::GetEnvironmentVariable('${SESSION_SOCKET_VAR}'))"`
    );
  }

  /**
   * Lines that take the guidance file `fileExpr` (a PowerShell expression)
   * and print its message literal wrapped in `json`, then exit. The move is
   * the claim: a second taker finds nothing.
   */
  private takeGuidance(fileExpr: string, json: { before: string; after: string }): string[] {
    const q = (s: string) => this.quote(s);
    return [
      `$g = ${fileExpr}`,
      'if (Test-Path -LiteralPath $g) {',
      "  $d = $g -replace '\\.json$', ('-' + [DateTimeOffset]::Now.ToUnixTimeMilliseconds() + '-' + $PID + '.json')",
      '  $moved = $true',
      '  try { Move-Item -LiteralPath $g -Destination $d -ErrorAction Stop } catch { $moved = $false }',
      `  if ($moved) { Write-Output (${q(json.before)} + [IO.File]::ReadAllText($d).Trim() + ${q(json.after)}); exit 0 }`,
      '}',
    ];
  }

  readonly stopHookFile = 'looper-stop-hook.ps1';

  renderStopHook(spec: StopHookSpec): string {
    const q = (s: string) => this.quote(s);
    return [
      '# generated by looper — Stop-hook gate',
      '[Console]::InputEncoding = [Text.Encoding]::UTF8',
      '$payload = [Console]::In.ReadToEnd()',
      `if (Test-Path -LiteralPath ${q(spec.doneFile)}) { [IO.File]::WriteAllText(${q(spec.stopJson)}, $payload); exit 0 }`,
      // Guidance that arrived after the agent's last tool call: the turn goes on with it.
      ...(spec.guidanceFile ? this.takeGuidance(q(spec.guidanceFile), STOP_GUIDANCE_JSON) : []),
      ...(spec.eventsFile ? this.takeGuidance(q(spec.eventsFile), STOP_GUIDANCE_JSON) : []),
      ...(spec.delegateFile ? this.takeGuidance(q(spec.delegateFile), STOP_GUIDANCE_JSON) : []),
      ...(spec.noticeFile ? this.takeGuidance(q(spec.noticeFile), STOP_GUIDANCE_JSON) : []),
      // Waiting on an agent it started: the turn ends with no reminder, and Looper brings the result in.
      ...(spec.delegateBusyFile
        ? [`if (Test-Path -LiteralPath ${q(spec.delegateBusyFile)}) { [IO.File]::WriteAllText(${q(spec.stopJson)}, $payload); exit 0 }`]
        : []),
      `if (-not (Test-Path -LiteralPath ${q(spec.reminderFile)})) {`,
      `  New-Item -ItemType File -Path ${q(spec.reminderFile)} -Force | Out-Null`,
      `  Write-Output ${q(spec.blockNoDone)}`,
      '  exit 0',
      '}',
      `[IO.File]::WriteAllText(${q(spec.stopJson)}, $payload)`,
      'exit 0',
      '',
    ].join('\r\n');
  }

  stopHookCommand(targetPath: string): string {
    // Forward slashes so the command survives whether claude runs hooks
    // through cmd or a bash-like shell on Windows.
    const p = targetPath.replace(/\\/g, '/');
    return `powershell -NoProfile -ExecutionPolicy Bypass -File "${p}"`;
  }

  readonly permissionHookFile = 'looper-permission-hook.ps1';

  renderPermissionHook(queueDir: string): string {
    const q = (s: string) => this.quote(s);
    return [
      '# generated by looper — task chat permission hook',
      '[Console]::InputEncoding = [Text.Encoding]::UTF8',
      '[Console]::OutputEncoding = [Text.Encoding]::UTF8',
      `$dir = ${q(queueDir)}`,
      'New-Item -ItemType Directory -Force -Path $dir | Out-Null',
      '$payload = [Console]::In.ReadToEnd()',
      '$id = "$([DateTime]::UtcNow.Ticks)-$PID"',
      '$req = Join-Path $dir "$id.req"',
      '$ans = Join-Path $dir "$id.ans"',
      '$cancel = Join-Path $dir "$id.cancel"',
      // Whole or not at all: Looper reads a request only once it has its final name.
      '[IO.File]::WriteAllText("$req.tmp", $payload)',
      'Move-Item -LiteralPath "$req.tmp" -Destination $req',
      // A .cancel: the request was answered elsewhere (a run's terminal), and Claude Code doesn't end the hook itself.
      'while (-not (Test-Path -LiteralPath $ans) -and -not (Test-Path -LiteralPath $cancel)) { Start-Sleep -Milliseconds 300 }',
      'if (Test-Path -LiteralPath $ans) { [Console]::Out.Write([IO.File]::ReadAllText($ans)) }',
      'Remove-Item -LiteralPath $req, $ans, $cancel -Force -ErrorAction SilentlyContinue',
      'exit 0',
      '',
    ].join('\r\n');
  }

  readonly subagentHookFile = 'looper-subagent-hook.ps1';

  renderSubagentHook(inboxDir: string): string {
    const q = (s: string) => this.quote(s);
    return [
      '# generated by looper — subagent message hook',
      '[Console]::InputEncoding = [Text.Encoding]::UTF8',
      '$payload = [Console]::In.ReadToEnd()',
      // agent_id and tool_name come before tool_input, so a tool's input or output can't supply them.
      `$head = ($payload -split '"tool_input"', 2)[0]`,
      `$m = [regex]::Match($head, '"agent_id"\\s*:\\s*"([A-Za-z0-9_-]+)"')`,
      'if (-not $m.Success) { exit 0 }',
      `$dir = Join-Path ${q(inboxDir)} $m.Groups[1].Value`,
      `if ($args[0] -eq 'start') { Write-Output ${q(SUBAGENT_START_JSON)}; exit 0 }`,
      // A hand-back ends the subagent's run: a message taken with it would never be read.
      `if ($head -match '"tool_name"\\s*:\\s*"${HANDBACK_TOOL}"') { exit 0 }`,
      ...this.takeGuidance(`(Join-Path $dir '${GUIDANCE_FILE}')`, guideHookJson('claude')),
      'exit 0',
      '',
    ].join('\r\n');
  }

  readonly guideHookFile = 'looper-guide-hook.ps1';

  renderGuideHook(format: GuideHookFormat, files?: GuideFiles): string {
    const json = guideHookJson(format);
    return [
      '# generated by looper — guidance hook',
      '$payload = [Console]::In.ReadToEnd()',
      // A subagent's tool call: the guidance is for the session's own agent.
      `if (${SUBAGENT_TEST}) { exit 0 }`,
      ...this.takeGuidance(files ? this.quote(files.guidance) : `(Join-Path $env:LOOPER_RUN_DIR '${GUIDANCE_FILE}')`, json),
      ...this.takeGuidance(files ? this.quote(files.events) : `(Join-Path $env:LOOPER_RUN_DIR '${EVENTS_FILE}')`, json),
      ...this.takeGuidance(files ? this.quote(files.delegate) : `(Join-Path $env:LOOPER_RUN_DIR '${DELEGATE_FILE}')`, json),
      ...this.takeGuidance(files ? this.quote(files.notice) : `(Join-Path $env:LOOPER_RUN_DIR '${NOTICE_FILE}')`, json),
      'exit 0',
      '',
    ].join('\r\n');
  }

  codexHookCommand(targetPath: string): string | null {
    const p = targetPath.replace(/\\/g, '/');
    return /^[\w/.:@+-]+$/.test(p) ? `powershell.exe -NoProfile -ExecutionPolicy Bypass -File ${p}` : null;
  }

  readonly notifyHookFile = 'looper-notify.ps1';

  renderNotifyHook(stopJson: string): string {
    return [
      '# generated by looper — codex notify hook',
      `[IO.File]::WriteAllText(${this.quote(stopJson)}, $args[0])`,
      '',
    ].join('\r\n');
  }

  notifyCommand(targetPath: string): string[] {
    // Forward slashes: the path rides inside a TOML basic string, where a backslash escapes.
    return ['powershell.exe', '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', targetPath.replace(/\\/g, '/')];
  }

  spawnSpec(launcherHostPath: string): SpawnSpec {
    const target = this.toTargetPath(launcherHostPath);
    return {
      command: 'powershell.exe',
      args: ['-NoLogo', '-ExecutionPolicy', 'Bypass', '-File', target],
    };
  }

  async killLeftovers(): Promise<void> {
    // taskkill /T on the launcher pid (done by the agent step) already takes the tree.
  }
}

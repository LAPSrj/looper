import type { LauncherSpec, SpawnSpec, Target, TargetContext } from './index';
import { guideHookJson, STOP_GUIDANCE_JSON, type GuideHookFormat, type StopHookSpec } from './stop-hook';
import { translatePath, translateToHost } from './paths';
import { GUIDANCE_FILE } from '../guidance';
import { wslDistroName } from '../host';

export class WindowsTarget implements Target {
  readonly kind = 'windows' as const;
  readonly launcherExt = '.ps1';

  doneHelperFile(command: string): string {
    return command + '.cmd';
  }
  private readonly mountPrefix: string;

  constructor(
    private readonly ctx: TargetContext,
    mountPrefix?: string,
  ) {
    this.mountPrefix = mountPrefix?.trim() || '/mnt';
  }

  toTargetPath(hostPath: string): string {
    return translatePath(hostPath, {
      host: this.ctx.host,
      targetKind: 'windows',
      wslMountPrefix: this.mountPrefix,
      hostDistro: wslDistroName(),
    });
  }

  toHostPath(targetPath: string): string {
    return translateToHost(targetPath, {
      host: this.ctx.host,
      targetKind: 'windows',
      wslMountPrefix: this.mountPrefix,
    });
  }

  quote(s: string): string {
    return `'${s.replace(/'/g, "''")}'`;
  }

  catFile(targetPath: string): string {
    // Windows PowerShell 5.1 passes embedded double quotes to native commands
    // unescaped, splitting the argument; pre-escaping them keeps the file's
    // content one argument (verified against node/codex argv).
    return `((Get-Content -Raw -LiteralPath ${this.quote(targetPath)}) -replace '"','\\"')`;
  }

  envRef(name: string): string {
    return `$env:${name}`;
  }

  renderLauncher(spec: LauncherSpec): string {
    const lines: string[] = [`# generated by looper — task ${spec.taskId} run ${spec.runId}`];
    for (const [k, v] of Object.entries(spec.env)) {
      lines.push(`$env:${k} = ${this.quote(v)}`);
    }
    lines.push(`$env:PATH = ${this.quote(spec.binDir)} + ';' + $env:PATH`);
    const statuses = spec.doneStatuses.map((s) => `'${s}'`).join(',');
    lines.push(
      `function ${spec.doneCommand} { param([Parameter(ValueFromRemainingArguments=$true)][string[]]$msg)`,
      "  $status = ''",
      `  if ($msg -and @(${statuses}) -contains $msg[0]) {`,
      '    $status = $msg[0]',
      '    $msg = if ($msg.Count -gt 1) { $msg[1..($msg.Count - 1)] } else { @() }',
      '  }',
      "  $text = if ($msg) { $msg -join ' ' } else { 'done' }",
      '  Set-Content -LiteralPath $env:LOOPER_DONE_FILE -Value ($status + [Environment]::NewLine + $text)',
      '}',
    );
    lines.push(`Set-Location -LiteralPath ${this.quote(spec.cwd)}`);
    lines.push(`if (-not $?) { Write-Error "looper: cannot cd to ${spec.cwd}"; exit 97 }`);
    lines.push(spec.body);
    lines.push('exit $LASTEXITCODE');
    lines.push('');
    return lines.join('\r\n');
  }

  renderDoneHelper(statuses: readonly string[]): string {
    return [
      '@echo off',
      'setlocal',
      'set "status="',
      'set "msg=%*"',
      ...statuses.map((s) => `if /i "%~1"=="${s}" goto strip`),
      'goto write',
      ':strip',
      'set "status=%~1"',
      'set "msg="',
      ':collect',
      'shift',
      'if "%~1"=="" goto write',
      'if defined msg (set "msg=%msg% %~1") else (set "msg=%~1")',
      'goto collect',
      ':write',
      'if not defined msg set "msg=done"',
      'echo.%status%> "%LOOPER_DONE_FILE%"',
      'echo.%msg%>> "%LOOPER_DONE_FILE%"',
      '',
    ].join('\r\n');
  }

  renderTextHelper(envVar: string, fallback: string): string {
    return [
      '@echo off',
      'setlocal',
      'set "msg=%*"',
      `if not defined msg set "msg=${fallback}"`,
      `echo.%msg%> "%${envVar}%"`,
      '',
    ].join('\r\n');
  }

  renderPipeHook(targetPath: string): string {
    // Works whether claude runs hooks through cmd or a bash-like shell on Windows.
    // .NET writes UTF-8 without BOM; the console input is declared UTF-8 so the payload survives.
    const p = targetPath.replace(/\\/g, '/');
    return (
      'powershell -NoProfile -Command "[Console]::InputEncoding=[Text.Encoding]::UTF8; ' +
      `[IO.File]::WriteAllText('${p}', [Console]::In.ReadToEnd())"`
    );
  }

  /**
   * Lines that take the guidance file `fileExpr` (a PowerShell expression)
   * and print its message literal wrapped in `json`, then exit. The move is
   * the claim: a second taker finds nothing.
   */
  private takeGuidance(fileExpr: string, json: { before: string; after: string }): string[] {
    const q = (s: string) => this.quote(s);
    return [
      `$g = ${fileExpr}`,
      'if (Test-Path -LiteralPath $g) {',
      "  $d = $g -replace '\\.json$', ('-' + [DateTimeOffset]::Now.ToUnixTimeMilliseconds() + '-' + $PID + '.json')",
      '  $moved = $true',
      '  try { Move-Item -LiteralPath $g -Destination $d -ErrorAction Stop } catch { $moved = $false }',
      `  if ($moved) { Write-Output (${q(json.before)} + [IO.File]::ReadAllText($d).Trim() + ${q(json.after)}); exit 0 }`,
      '}',
    ];
  }

  readonly stopHookFile = 'looper-stop-hook.ps1';

  renderStopHook(spec: StopHookSpec): string {
    const q = (s: string) => this.quote(s);
    return [
      '# generated by looper — Stop-hook gate',
      '[Console]::InputEncoding = [Text.Encoding]::UTF8',
      '$payload = [Console]::In.ReadToEnd()',
      `if (Test-Path -LiteralPath ${q(spec.doneFile)}) { [IO.File]::WriteAllText(${q(spec.stopJson)}, $payload); exit 0 }`,
      // Guidance that arrived after the agent's last tool call: the turn goes on with it.
      ...(spec.guidanceFile ? this.takeGuidance(q(spec.guidanceFile), STOP_GUIDANCE_JSON) : []),
      '$running = @()',
      "try { $running = @(($payload | ConvertFrom-Json).background_tasks | Where-Object { $_.status -eq 'running' }) } catch {}",
      `if ($running.Count -gt 0) { Write-Output ${q(spec.blockBackground)}; exit 0 }`,
      `if (-not (Test-Path -LiteralPath ${q(spec.reminderFile)})) {`,
      `  New-Item -ItemType File -Path ${q(spec.reminderFile)} -Force | Out-Null`,
      `  Write-Output ${q(spec.blockNoDone)}`,
      '  exit 0',
      '}',
      `[IO.File]::WriteAllText(${q(spec.stopJson)}, $payload)`,
      'exit 0',
      '',
    ].join('\r\n');
  }

  stopHookCommand(targetPath: string): string {
    // Forward slashes so the command survives whether claude runs hooks
    // through cmd or a bash-like shell on Windows.
    const p = targetPath.replace(/\\/g, '/');
    return `powershell -NoProfile -ExecutionPolicy Bypass -File "${p}"`;
  }

  readonly guideHookFile = 'looper-guide-hook.ps1';

  renderGuideHook(format: GuideHookFormat, guidanceFile?: string): string {
    return [
      '# generated by looper — guidance hook',
      '$payload = [Console]::In.ReadToEnd()',
      // A subagent's tool call: the guidance is for the session's own agent.
      `if (($payload -split '"tool_input"', 2)[0] -match '"agent_id"\\s*:') { exit 0 }`,
      ...this.takeGuidance(
        guidanceFile ? this.quote(guidanceFile) : `(Join-Path $env:LOOPER_RUN_DIR '${GUIDANCE_FILE}')`,
        guideHookJson(format),
      ),
      'exit 0',
      '',
    ].join('\r\n');
  }

  codexHookCommand(targetPath: string): string | null {
    const p = targetPath.replace(/\\/g, '/');
    return /^[\w/.:@+-]+$/.test(p) ? `powershell.exe -NoProfile -ExecutionPolicy Bypass -File ${p}` : null;
  }

  readonly notifyHookFile = 'looper-notify.ps1';

  renderNotifyHook(stopJson: string): string {
    return [
      '# generated by looper — codex notify hook',
      `[IO.File]::WriteAllText(${this.quote(stopJson)}, $args[0])`,
      '',
    ].join('\r\n');
  }

  notifyCommand(targetPath: string): string[] {
    // Forward slashes: the path rides inside a TOML basic string, where a backslash escapes.
    return ['powershell.exe', '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', targetPath.replace(/\\/g, '/')];
  }

  spawnSpec(launcherHostPath: string): SpawnSpec {
    const target = this.toTargetPath(launcherHostPath);
    return {
      command: 'powershell.exe',
      args: ['-NoLogo', '-ExecutionPolicy', 'Bypass', '-File', target],
    };
  }

  async killLeftovers(): Promise<void> {
    // taskkill /T on the launcher pid (done by the agent step) already takes the tree.
  }
}

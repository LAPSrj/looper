import type { LauncherSpec, SpawnSpec, Target, TargetContext } from './index';
import { STOP_BLOCK_BACKGROUND, STOP_BLOCK_NO_DONE, type StopHookSpec } from './stop-hook';
import { translatePath } from './paths';
import { wslDistroName } from '../host';

export class WindowsTarget implements Target {
  readonly kind = 'windows' as const;
  readonly launcherExt = '.ps1';
  readonly doneHelperFile = 'looper-done.cmd';
  private readonly mountPrefix: string;

  constructor(
    private readonly ctx: TargetContext,
    mountPrefix?: string,
  ) {
    this.mountPrefix = mountPrefix?.trim() || '/mnt';
  }

  toTargetPath(hostPath: string): string {
    return translatePath(hostPath, {
      host: this.ctx.host,
      targetKind: 'windows',
      wslMountPrefix: this.mountPrefix,
      hostDistro: wslDistroName(),
    });
  }

  quote(s: string): string {
    return `'${s.replace(/'/g, "''")}'`;
  }

  catFile(targetPath: string): string {
    return `(Get-Content -Raw -LiteralPath ${this.quote(targetPath)})`;
  }

  envRef(name: string): string {
    return `$env:${name}`;
  }

  renderLauncher(spec: LauncherSpec): string {
    const lines: string[] = [`# generated by looper — task ${spec.taskId} run ${spec.runId}`];
    for (const [k, v] of Object.entries(spec.env)) {
      lines.push(`$env:${k} = ${this.quote(v)}`);
    }
    lines.push(`$env:PATH = ${this.quote(spec.binDir)} + ';' + $env:PATH`);
    lines.push(
      'function looper-done { param([Parameter(ValueFromRemainingArguments=$true)][string[]]$msg)',
      "  $status = 'success'",
      "  if ($msg -and @('success','warning','error') -contains $msg[0]) {",
      '    $status = $msg[0]',
      '    $msg = if ($msg.Count -gt 1) { $msg[1..($msg.Count - 1)] } else { @() }',
      '  }',
      "  $text = if ($msg) { $msg -join ' ' } else { 'done' }",
      '  Set-Content -LiteralPath $env:LOOPER_DONE_FILE -Value ($status + [Environment]::NewLine + $text)',
      '}',
    );
    lines.push(`Set-Location -LiteralPath ${this.quote(spec.cwd)}`);
    lines.push(`if (-not $?) { Write-Error "looper: cannot cd to ${spec.cwd}"; exit 97 }`);
    lines.push(spec.body);
    lines.push('exit $LASTEXITCODE');
    lines.push('');
    return lines.join('\r\n');
  }

  renderDoneHelper(): string {
    return [
      '@echo off',
      'setlocal',
      'set "status=success"',
      'set "msg=%*"',
      'if /i "%~1"=="success" goto strip',
      'if /i "%~1"=="warning" goto strip',
      'if /i "%~1"=="error" goto strip',
      'goto write',
      ':strip',
      'set "status=%~1"',
      'set "msg="',
      ':collect',
      'shift',
      'if "%~1"=="" goto write',
      'if defined msg (set "msg=%msg% %~1") else (set "msg=%~1")',
      'goto collect',
      ':write',
      'if not defined msg set "msg=done"',
      'echo %status%> "%LOOPER_DONE_FILE%"',
      'echo %msg%>> "%LOOPER_DONE_FILE%"',
      '',
    ].join('\r\n');
  }

  renderPipeHook(targetPath: string): string {
    // Works whether claude runs hooks through cmd or a bash-like shell on Windows.
    // .NET writes UTF-8 without BOM; the console input is declared UTF-8 so the payload survives.
    const p = targetPath.replace(/\\/g, '/');
    return (
      'powershell -NoProfile -Command "[Console]::InputEncoding=[Text.Encoding]::UTF8; ' +
      `[IO.File]::WriteAllText('${p}', [Console]::In.ReadToEnd())"`
    );
  }

  readonly stopHookFile = 'looper-stop-hook.ps1';

  renderStopHook(spec: StopHookSpec): string {
    const q = (s: string) => this.quote(s);
    return [
      '# generated by looper — Stop-hook gate',
      '[Console]::InputEncoding = [Text.Encoding]::UTF8',
      '$payload = [Console]::In.ReadToEnd()',
      `if (Test-Path -LiteralPath ${q(spec.doneFile)}) { [IO.File]::WriteAllText(${q(spec.stopJson)}, $payload); exit 0 }`,
      '$running = @()',
      "try { $running = @(($payload | ConvertFrom-Json).background_tasks | Where-Object { $_.status -eq 'running' }) } catch {}",
      `if ($running.Count -gt 0) { Write-Output ${q(STOP_BLOCK_BACKGROUND)}; exit 0 }`,
      `if (-not (Test-Path -LiteralPath ${q(spec.reminderFile)})) {`,
      `  New-Item -ItemType File -Path ${q(spec.reminderFile)} -Force | Out-Null`,
      `  Write-Output ${q(STOP_BLOCK_NO_DONE)}`,
      '  exit 0',
      '}',
      `[IO.File]::WriteAllText(${q(spec.stopJson)}, $payload)`,
      'exit 0',
      '',
    ].join('\r\n');
  }

  stopHookCommand(targetPath: string): string {
    // Forward slashes so the command survives whether claude runs hooks
    // through cmd or a bash-like shell on Windows.
    const p = targetPath.replace(/\\/g, '/');
    return `powershell -NoProfile -ExecutionPolicy Bypass -File "${p}"`;
  }

  spawnSpec(launcherHostPath: string): SpawnSpec {
    const target = this.toTargetPath(launcherHostPath);
    return {
      command: 'powershell.exe',
      args: ['-NoLogo', '-ExecutionPolicy', 'Bypass', '-File', target],
    };
  }

  async killLeftovers(): Promise<void> {
    // taskkill /T on the launcher pid (done by the agent step) already takes the tree.
  }
}

/**
 * Case pattern for a hook payload's head (everything before "tool_input") that
 * comes from a subagent: claude sends agent_id only on a subagent's call, and
 * before tool_input, so the command or a tool's output can't supply it.
 */
const SUBAGENT_PATTERN = `*'"agent_id":'* | *'"agent_id": '*`;

/** A helper script's name as its shell sees it. */
const SCRIPT_NAME = '"${0##*/}"';

/** A helper's first line: --help or -h prints its usage (`name` is a shell word) and signals nothing. */
const HELP_CHECK = (name: string, args: string, leave: 'exit' | 'return'): string =>
  `case "$1" in -h|--help) printf 'usage: %s %s\\n' ${name} ${shellQuote(args)}; ${leave} 0;; esac;`;

/** The done command's first line: while an agent the session started is still going, it prints why and fails. */
const DELEGATE_REFUSAL = (leave: 'exit' | 'return'): string =>
  `if [ -n "$${DELEGATE_BUSY_VAR}" ] && [ -e "$${DELEGATE_BUSY_VAR}" ]; then cat "$${DELEGATE_BUSY_VAR}" >&2; ${leave} 1; fi;`;

/** A helper's first line: run by a session other than the one its run started (a nested claude), it refuses. */
const NESTED_CHECK = (leave: 'exit' | 'return'): string =>
  `if [ -n "$${SESSION_SOCKET_VAR}" ] && [ -s "$${SOCKET_FILE_VAR}" ] && [ "$(cat "$${SOCKET_FILE_VAR}")" != "$${SESSION_SOCKET_VAR}" ]; then echo '${NESTED_REFUSAL.replace(/'/g, `'\\''`)}' >&2; ${leave} 1; fi;`;

/**
 * Prints the pid of each process whose environment holds `marker` exactly.
 * One grep reads all of /proc: a tr and a grep per process took about 1 s.
 * macOS has no /proc, and BSD ps's `e` flag appends each (same-user)
 * process's environment to its command line, so the marker is an exact field.
 */
function listScript(marker: string, mac: boolean): string {
  return mac
    ? `ps axeww -o pid= -o command= | awk -v m=${marker} '{ for (i = 2; i <= NF; i++) if ($i == m) { print $1; break } }'`
    : `grep -lsxzF -- ${marker} /proc/[0-9]*/environ | sed 's#^/proc/##; s#/environ$##'`;
}

/** TERM the marked processes, wait up to 1.5 s for them to exit, then KILL any process still marked. */
function killScript(marker: string, mac: boolean): string {
  const list = listScript(marker, mac);
  return (
    `pids=$(${list}); [ -z "$pids" ] && exit 0; kill -TERM $pids 2>/dev/null; ` +
    `n=0; while [ $n -lt 15 ]; do alive=; for p in $pids; do kill -0 "$p" 2>/dev/null && alive=1; done; ` +
    `[ -z "$alive" ] && break; sleep 0.1; n=$((n + 1)); done; ` +
    `pids=$(${list}); [ -n "$pids" ] && kill -KILL $pids 2>/dev/null; exit 0`
  );
}

function shellQuote(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

export class BashTarget implements Target {
  readonly kind = 'wsl' as const;
  readonly launcherExt = '.sh';

  doneHelperFile(command: string): string {
    return command;
  }
  private readonly shellParts: string[];
  private readonly mountPrefix: string;

  constructor(
    private readonly ctx: TargetContext,
    private readonly distro: string | undefined,
    shell?: string,
    mountPrefix?: string,
  ) {
    this.shellParts = (shell?.trim() || DEFAULT_SHELL).split(/\s+/);
    this.mountPrefix = mountPrefix?.trim() || '/mnt';
  }

  toTargetPath(hostPath: string): string {
    return translatePath(hostPath, {
      host: this.ctx.host,
      targetKind: 'wsl',
      wslMountPrefix: this.mountPrefix,
      hostDistro: wslDistroName(),
    });
  }

  toHostPath(targetPath: string): string {
    return translateToHost(targetPath, {
      host: this.ctx.host,
      targetKind: 'wsl',
      wslMountPrefix: this.mountPrefix,
      // An environment on the default distro reaches its files under the default distro's name.
      targetDistro: this.distro || detectedDefaultWslDistro(),
    });
  }

  quote(s: string): string {
    return shellQuote(s);
  }

  catFile(targetPath: string): string {
    return `"$(cat ${this.quote(targetPath)})"`;
  }

  envRef(name: string): string {
    return `"$${name}"`;
  }

  renderLauncher(spec: LauncherSpec): string {
    const lines: string[] = [
      '#!/usr/bin/env bash',
      `# generated by looper — task ${spec.taskId} run ${spec.runId}`,
    ];
    for (const [k, v] of Object.entries(spec.env)) {
      lines.push(`export ${k}=${this.quote(v)}`);
    }
    lines.push(`export PATH=${this.quote(spec.binDir)}":$PATH"`);
    if (spec.doneCommand) {
      const statuses = spec.doneStatuses ?? [];
      lines.push(
        `${spec.doneCommand}() { ${HELP_CHECK(shellQuote(spec.doneCommand), doneUsage(statuses), 'return')} ${NESTED_CHECK('return')} ${DELEGATE_REFUSAL('return')} local s=; case "$1" in ${statuses.join('|')}) s="$1"; shift;; esac; printf '%s\\n%s\\n' "$s" "\${*:-done}" > "$LOOPER_DONE_FILE"; }`,
      );
      lines.push(`export -f ${spec.doneCommand} 2>/dev/null`);
    }
    lines.push(
      `cd ${this.quote(spec.cwd)} || { echo "looper: cannot cd to ${spec.cwd}" >&2; exit 97; }`,
    );
    lines.push(spec.body);
    lines.push('');
    return lines.join('\n');
  }

  renderDoneHelper(statuses: readonly string[]): string {
    return [
      '#!/usr/bin/env bash',
      HELP_CHECK(SCRIPT_NAME, doneUsage(statuses), 'exit'),
      NESTED_CHECK('exit'),
      DELEGATE_REFUSAL('exit'),
      's=',
      `case "$1" in ${statuses.join('|')}) s="$1"; shift;; esac`,
      `printf '%s\\n%s\\n' "$s" "\${*:-done}" > "$LOOPER_DONE_FILE"`,
      '',
    ].join('\n');
  }

  renderTextHelper(envVar: string, fallback: string): string {
    return [
      '#!/usr/bin/env bash',
      HELP_CHECK(SCRIPT_NAME, REASON_USAGE, 'exit'),
      NESTED_CHECK('exit'),
      `printf '%s\\n' "\${*:-${fallback}}" > "$${envVar}"`,
      '',
    ].join('\n');
  }

  renderStatusHelper(status: string, fallback: string): string {
    return [
      '#!/usr/bin/env bash',
      HELP_CHECK(SCRIPT_NAME, REASON_USAGE, 'exit'),
      NESTED_CHECK('exit'),
      `printf '%s\\n%s\\n' ${this.quote(status)} "\${*:-${fallback}}" > "$LOOPER_DONE_FILE"`,
      '',
    ].join('\n');
  }

  renderPipeHook(targetPath: string): string {
    return `cat > ${this.quote(targetPath)}`;
  }

  renderSessionStartHook(sessionJson: string, socketFile: string): string {
    return `cat > ${this.quote(sessionJson)}; printf '%s' "$${SESSION_SOCKET_VAR}" > ${this.quote(socketFile)}`;
  }

  /**
   * Lines that take the guidance file `fileExpr` (an already-quoted shell
   * word) and print its message literal wrapped in `json`, then exit. The
   * rename is the claim: a second taker finds nothing.
   */
  private takeGuidance(fileExpr: string, json: { before: string; after: string }): string[] {
    const q = (s: string) => this.quote(s);
    return [
      `g=${fileExpr}`,
      'if [ -e "$g" ]; then',
      '  d="${g%.json}-$(date +%s)-$$.json"',
      `  if mv "$g" "$d" 2>/dev/null; then printf '%s%s%s\\n' ${q(json.before)} "$(cat "$d")" ${q(json.after)}; exit 0; fi`,
      'fi',
    ];
  }

  readonly stopHookFile = 'looper-stop-hook';

  renderStopHook(spec: StopHookSpec): string {
    const q = (s: string) => this.quote(s);
    return [
      '#!/usr/bin/env bash',
      '# generated by looper — Stop-hook gate',
      'payload="$(cat)"',
      `if [ -e ${q(spec.doneFile)} ]; then printf '%s' "$payload" > ${q(spec.stopJson)}; exit 0; fi`,
      // Guidance that arrived after the agent's last tool call: the turn goes on with it.
      ...(spec.guidanceFile ? this.takeGuidance(q(spec.guidanceFile), STOP_GUIDANCE_JSON) : []),
      ...(spec.eventsFile ? this.takeGuidance(q(spec.eventsFile), STOP_GUIDANCE_JSON) : []),
      ...(spec.delegateFile ? this.takeGuidance(q(spec.delegateFile), STOP_GUIDANCE_JSON) : []),
      ...(spec.noticeFile ? this.takeGuidance(q(spec.noticeFile), STOP_GUIDANCE_JSON) : []),
      // Waiting on an agent it started: the turn ends with no reminder, and Looper brings the result in.
      ...(spec.delegateBusyFile ? [`if [ -e ${q(spec.delegateBusyFile)} ]; then printf '%s' "$payload" > ${q(spec.stopJson)}; exit 0; fi`] : []),
      `if [ ! -e ${q(spec.reminderFile)} ]; then`,
      `  : > ${q(spec.reminderFile)}`,
      `  printf '%s\\n' ${q(spec.blockNoDone)}`,
      '  exit 0',
      'fi',
      `printf '%s' "$payload" > ${q(spec.stopJson)}`,
      'exit 0',
      '',
    ].join('\n');
  }

  stopHookCommand(targetPath: string): string {
    return `bash ${this.quote(targetPath)}`;
  }

  readonly permissionHookFile = 'looper-permission-hook';

  renderPermissionHook(queueDir: string): string {
    const q = (s: string) => this.quote(s);
    return [
      '#!/usr/bin/env bash',
      '# generated by looper — task chat permission hook',
      `dir=${q(queueDir)}`,
      'mkdir -p "$dir"',
      'payload="$(cat)"',
      'id="$(date +%s%N)-$$"',
      // Whole or not at all: Looper reads a request only once it has its final name.
      `printf '%s' "$payload" > "$dir/$id.req.tmp" && mv "$dir/$id.req.tmp" "$dir/$id.req"`,
      // A .cancel: the request was answered elsewhere (a run's terminal), and Claude Code doesn't end the hook itself.
      'while [ ! -e "$dir/$id.ans" ] && [ ! -e "$dir/$id.cancel" ]; do sleep 0.3; done',
      '[ -e "$dir/$id.ans" ] && cat "$dir/$id.ans"',
      'rm -f "$dir/$id.req" "$dir/$id.ans" "$dir/$id.cancel"',
      'exit 0',
      '',
    ].join('\n');
  }

  readonly subagentHookFile = 'looper-subagent-hook';

  renderSubagentHook(inboxDir: string): string {
    const q = (s: string) => this.quote(s);
    const file = `${q(inboxDir)}"/$id/${GUIDANCE_FILE}"`;
    return [
      '#!/usr/bin/env bash',
      '# generated by looper — subagent message hook',
      'payload="$(cat)"',
      // agent_id and tool_name come before tool_input, so a tool's input or output can't supply them.
      `head=\${payload%%'"tool_input"'*}`,
      `re='"agent_id": *"([A-Za-z0-9_-]+)"'`,
      '[[ $head =~ $re ]] || exit 0',
      'id=${BASH_REMATCH[1]}',
      `if [ "$1" = start ]; then printf '%s\\n' ${q(SUBAGENT_START_JSON)}; exit 0; fi`,
      // A hand-back ends the subagent's run: a message taken with it would never be read.
      `handback='"tool_name": *"${HANDBACK_TOOL}"'`,
      '[[ $head =~ $handback ]] && exit 0',
      ...this.takeGuidance(file, guideHookJson('claude')),
      'exit 0',
      '',
    ].join('\n');
  }

  readonly guideHookFile = 'looper-guide-hook';

  renderGuideHook(format: GuideHookFormat, files?: GuideFiles): string {
    const json = guideHookJson(format);
    return [
      '#!/usr/bin/env bash',
      '# generated by looper — guidance hook',
      'payload="$(cat)"',
      // A subagent's tool call: the guidance is for the session's own agent.
      `case "\${payload%%'"tool_input"'*}" in ${SUBAGENT_PATTERN}) exit 0 ;; esac`,
      ...this.takeGuidance(files ? this.quote(files.guidance) : `"$LOOPER_RUN_DIR/${GUIDANCE_FILE}"`, json),
      ...this.takeGuidance(files ? this.quote(files.events) : `"$LOOPER_RUN_DIR/${EVENTS_FILE}"`, json),
      ...this.takeGuidance(files ? this.quote(files.delegate) : `"$LOOPER_RUN_DIR/${DELEGATE_FILE}"`, json),
      ...this.takeGuidance(files ? this.quote(files.notice) : `"$LOOPER_RUN_DIR/${NOTICE_FILE}"`, json),
      'exit 0',
      '',
    ].join('\n');
  }

  codexHookCommand(targetPath: string): string | null {
    return /^[\w/.:@+-]+$/.test(targetPath) ? `bash ${targetPath}` : null;
  }

  readonly notifyHookFile = 'looper-notify';

  renderNotifyHook(stopJson: string): string {
    return [
      '#!/usr/bin/env bash',
      '# generated by looper — codex notify hook',
      `printf '%s' "$1" > ${this.quote(stopJson)}`,
      '',
    ].join('\n');
  }

  notifyCommand(targetPath: string): string[] {
    return ['bash', targetPath];
  }

  renderCodexHomeWrapper(command: string, codexHome: string): string {
    return [
      'real="${CODEX_HOME:-$HOME/.codex}"',
      `home=${this.quote(codexHome)}`,
      'mkdir -p "$home"',
      'if [ ! -f "$home/auth.json" ] && [ -f "$real/auth.json" ]; then',
      '  cp "$real/auth.json" "$home/auth.json" && cp "$real/auth.json" "$home/.auth-base"',
      '  chmod 600 "$home/auth.json" "$home/.auth-base" 2>/dev/null',
      'fi',
      `CODEX_HOME="$home" ${command}`,
      'code=$?',
      'if [ -f "$home/auth.json" ] && ! cmp -s "$home/auth.json" "$home/.auth-base"; then',
      '  if cmp -s "$real/auth.json" "$home/.auth-base"; then',
      '    cp "$home/auth.json" "$real/auth.json.looper" && chmod 600 "$real/auth.json.looper" && mv -f "$real/auth.json.looper" "$real/auth.json"',
      '  fi',
      '  cp "$home/auth.json" "$home/.auth-base"',
      'fi',
      'exit $code',
    ].join('\n');
  }

  renderRequestHelpers(ops: Record<string, string>, opts: RequestHelperOpts): Record<string, string> {
    const out: Record<string, string> = {};
    for (const [command, op] of Object.entries(ops)) {
      out[command] = [
        '#!/usr/bin/env bash',
        `# generated by looper — request helper (${command})`,
        NESTED_CHECK('exit'),
        `d="$${opts.dirVar}"`,
        'rid="$(date +%s)-$$-$RANDOM"',
        'mkdir -p "$d/requests" "$d/responses"',
        // The op, the caller's folder (for relative paths), then one line per
        // argument; the rename makes the request appear whole.
        `{ printf '%s\\n' ${this.quote(op)} "$PWD"; for a in "$@"; do printf '%s\\n' "$a"; done; } > "$d/requests/$rid.tmp"`,
        'mv "$d/requests/$rid.tmp" "$d/requests/$rid.req"',
        `for _ in $(seq 1 ${requestPolls(opts)}); do`,
        '  if [ -e "$d/responses/$rid.code" ]; then',
        '    cat "$d/responses/$rid.out" 2>/dev/null',
        '    code="$(cat "$d/responses/$rid.code")"',
        '    rm -f "$d/responses/$rid.out" "$d/responses/$rid.code"',
        '    exit "${code:-1}"',
        '  fi',
        '  sleep 0.5',
        'done',
        `echo ${this.quote(`looper: no answer from Looper (${opts.hint})`)} >&2`,
        'exit 1',
        '',
      ].join('\n');
    }
    return out;
  }

  renderCliHelper(paths: { script: string; home: string; exe: string }): Record<string, string> {
    const script = this.quote(this.toTargetPath(paths.script));
    const lines = [
      '#!/usr/bin/env bash',
      "# generated by looper — Looper's command-line tool",
      `[ -f ${script} ] || { echo "looper: Looper hasn't set up its command-line tool yet; try again in a minute" >&2; exit 1; }`,
    ];
    if (this.ctx.host === 'windows') {
      lines.push(
        `if command -v node >/dev/null 2>&1; then LOOPER_HOME=${this.quote(this.toTargetPath(paths.home))} exec node ${script} "$@"; fi`,
        // Without Node here, Looper's executable runs it on Windows, as the Git addon's askpass does.
        `ELECTRON_RUN_AS_NODE=1 LOOPER_HOME=${this.quote(paths.home)} WSLENV="\${WSLENV:+\$WSLENV:}ELECTRON_RUN_AS_NODE:LOOPER_HOME" exec ${this.quote(this.toTargetPath(paths.exe))} ${this.quote(paths.script)} "$@"`,
      );
    } else {
      lines.push(`ELECTRON_RUN_AS_NODE=1 LOOPER_HOME=${this.quote(paths.home)} exec ${this.quote(paths.exe)} ${script} "$@"`);
    }
    return { looper: lines.join('\n') + '\n' };
  }

  private wslPrefix(sep: '--' | '-e' = '--'): string[] {
    if (this.ctx.host !== 'windows') return [];
    return this.distro ? ['wsl.exe', '-d', this.distro, sep] : ['wsl.exe', sep];
  }

  spawnSpec(launcherHostPath: string): SpawnSpec {
    const target = this.toTargetPath(launcherHostPath);
    const [cmd, ...flags] = this.shellParts;
    const sourceCmd = `source ${this.quote(target)}`;
    const full = [...this.wslPrefix(), cmd, ...flags, sourceCmd];
    return { command: full[0], args: full.slice(1) };
  }

  private runShell(script: string, timeoutMs: number): Promise<void> {
    // `--` hands the line to the distro's shell, which would expand the script's `$` before bash -c sees it.
    const full = [...this.wslPrefix('-e'), 'bash', '-c', script];
    return execOffThread(full[0], full.slice(1), { timeout: timeoutMs, windowsHide: true }).then(() => undefined);
  }

  async killLeftovers(runId: string): Promise<void> {
    await this.runShell(killScript(this.quote(`LOOPER_RUN=${runId}`), this.ctx.host === 'mac'), 20_000);
  }
}

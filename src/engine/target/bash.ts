import { execFile } from 'node:child_process';
import type { LauncherSpec, SpawnSpec, Target, TargetContext } from './index';
import { guideHookJson, STOP_GUIDANCE_JSON, type GuideHookFormat, type StopHookSpec } from './stop-hook';
import { translatePath, translateToHost } from './paths';
import { GUIDANCE_FILE, NOTICE_FILE } from '../guidance';
import { detectedDefaultWslDistro, wslDistroName } from '../host';
import { DEFAULT_SHELL } from '../../shared/environments';

/**
 * Case pattern for a hook payload's head (everything before "tool_input") that
 * comes from a subagent: claude sends agent_id only on a subagent's call, and
 * before tool_input, so the command or a tool's output can't supply it.
 */
const SUBAGENT_PATTERN = `*'"agent_id":'* | *'"agent_id": '*`;

/** Kill script: scan /proc for processes whose environment carries the run marker. */
function killScript(runId: string, signal: string): string {
  return (
    `for p in /proc/[0-9]*; do ` +
    `if tr '\\0' '\\n' < "$p/environ" 2>/dev/null | grep -qx 'LOOPER_RUN=${runId}'; then ` +
    `kill -${signal} "\${p#/proc/}" 2>/dev/null; fi; done; exit 0`
  );
}

/**
 * macOS has no /proc: BSD ps's `e` flag appends each (same-user) process's
 * environment to its command line, so match the run marker as an exact field.
 */
function killScriptMac(runId: string, signal: string): string {
  return (
    `ps axeww -o pid= -o command= | ` +
    `awk -v m='LOOPER_RUN=${runId}' '{ for (i = 2; i <= NF; i++) if ($i == m) { print $1; break } }' | ` +
    `while read -r p; do kill -${signal} "$p" 2>/dev/null; done; exit 0`
  );
}

export class BashTarget implements Target {
  readonly kind = 'wsl' as const;
  readonly launcherExt = '.sh';

  doneHelperFile(command: string): string {
    return command;
  }
  private readonly shellParts: string[];
  private readonly mountPrefix: string;

  constructor(
    private readonly ctx: TargetContext,
    private readonly distro: string | undefined,
    shell?: string,
    mountPrefix?: string,
  ) {
    this.shellParts = (shell?.trim() || DEFAULT_SHELL).split(/\s+/);
    this.mountPrefix = mountPrefix?.trim() || '/mnt';
  }

  toTargetPath(hostPath: string): string {
    return translatePath(hostPath, {
      host: this.ctx.host,
      targetKind: 'wsl',
      wslMountPrefix: this.mountPrefix,
      hostDistro: wslDistroName(),
    });
  }

  toHostPath(targetPath: string): string {
    return translateToHost(targetPath, {
      host: this.ctx.host,
      targetKind: 'wsl',
      wslMountPrefix: this.mountPrefix,
      // An environment on the default distro reaches its files under the default distro's name.
      targetDistro: this.distro || detectedDefaultWslDistro(),
    });
  }

  quote(s: string): string {
    return `'${s.replace(/'/g, `'\\''`)}'`;
  }

  catFile(targetPath: string): string {
    return `"$(cat ${this.quote(targetPath)})"`;
  }

  envRef(name: string): string {
    return `"$${name}"`;
  }

  renderLauncher(spec: LauncherSpec): string {
    const lines: string[] = [
      '#!/usr/bin/env bash',
      `# generated by looper — task ${spec.taskId} run ${spec.runId}`,
    ];
    for (const [k, v] of Object.entries(spec.env)) {
      lines.push(`export ${k}=${this.quote(v)}`);
    }
    lines.push(`export PATH=${this.quote(spec.binDir)}":$PATH"`);
    const statuses = spec.doneStatuses.join('|');
    lines.push(
      `${spec.doneCommand}() { local s=; case "$1" in ${statuses}) s="$1"; shift;; esac; printf '%s\\n%s\\n' "$s" "\${*:-done}" > "$LOOPER_DONE_FILE"; }`,
    );
    lines.push(`export -f ${spec.doneCommand} 2>/dev/null`);
    lines.push(
      `cd ${this.quote(spec.cwd)} || { echo "looper: cannot cd to ${spec.cwd}" >&2; exit 97; }`,
    );
    lines.push(spec.body);
    lines.push('');
    return lines.join('\n');
  }

  renderDoneHelper(statuses: readonly string[]): string {
    return [
      '#!/usr/bin/env bash',
      's=',
      `case "$1" in ${statuses.join('|')}) s="$1"; shift;; esac`,
      `printf '%s\\n%s\\n' "$s" "\${*:-done}" > "$LOOPER_DONE_FILE"`,
      '',
    ].join('\n');
  }

  renderTextHelper(envVar: string, fallback: string): string {
    return [
      '#!/usr/bin/env bash',
      `printf '%s\\n' "\${*:-${fallback}}" > "$${envVar}"`,
      '',
    ].join('\n');
  }

  renderStatusHelper(status: string, fallback: string): string {
    return [
      '#!/usr/bin/env bash',
      `printf '%s\\n%s\\n' ${this.quote(status)} "\${*:-${fallback}}" > "$LOOPER_DONE_FILE"`,
      '',
    ].join('\n');
  }

  renderPipeHook(targetPath: string): string {
    return `cat > ${this.quote(targetPath)}`;
  }

  /**
   * Lines that take the guidance file `fileExpr` (an already-quoted shell
   * word) and print its message literal wrapped in `json`, then exit. The
   * rename is the claim: a second taker finds nothing.
   */
  private takeGuidance(fileExpr: string, json: { before: string; after: string }): string[] {
    const q = (s: string) => this.quote(s);
    return [
      `g=${fileExpr}`,
      'if [ -e "$g" ]; then',
      '  d="${g%.json}-$(date +%s)-$$.json"',
      `  if mv "$g" "$d" 2>/dev/null; then printf '%s%s%s\\n' ${q(json.before)} "$(cat "$d")" ${q(json.after)}; exit 0; fi`,
      'fi',
    ];
  }

  readonly stopHookFile = 'looper-stop-hook';

  renderStopHook(spec: StopHookSpec): string {
    const q = (s: string) => this.quote(s);
    return [
      '#!/usr/bin/env bash',
      '# generated by looper — Stop-hook gate',
      'payload="$(cat)"',
      `if [ -e ${q(spec.doneFile)} ]; then printf '%s' "$payload" > ${q(spec.stopJson)}; exit 0; fi`,
      // Guidance that arrived after the agent's last tool call: the turn goes on with it.
      ...(spec.guidanceFile ? this.takeGuidance(q(spec.guidanceFile), STOP_GUIDANCE_JSON) : []),
      ...(spec.noticeFile ? this.takeGuidance(q(spec.noticeFile), STOP_GUIDANCE_JSON) : []),
      '# Emit the background_tasks array up to its real closing ], tracking',
      '# string/escape state and bracket depth, with whitespace outside strings',
      '# dropped — so structural matches cannot hit string contents.',
      'scan_tasks() {',
      '  local rest=$1 out= c i n depth=1 instr=0 esc=0',
      '  n=${#rest}',
      '  for ((i = 0; i < n; i++)); do',
      '    c=${rest:i:1}',
      '    if ((esc)); then esc=0; out+=$c; continue; fi',
      '    if ((instr)); then',
      '      case $c in',
      "      '\\') esc=1 ;;",
      '      \'"\') instr=0 ;;',
      '      esac',
      '      out+=$c',
      '      continue',
      '    fi',
      '    case $c in',
      "    ' ' | $'\\t' | $'\\n' | $'\\r') continue ;;",
      '    \'"\') instr=1 ;;',
      "    '[' | '{') ((depth++)) ;;",
      "    '}') ((depth--)) ;;",
      "    ']')",
      '      ((depth--))',
      '      if ((depth == 0)); then break; fi',
      '      ;;',
      '    esac',
      '    out+=$c',
      '  done',
      `  printf '%s' "$out"`,
      '}',
      // Quotes inside JSON string values arrive escaped (\"), so a literal
      // "background_tasks": match can only hit the structural key.
      `key='"background_tasks":'`,
      'rest=${payload#*"$key"}',
      'if [ "$rest" != "$payload" ]; then',
      '  rest="${rest#"${rest%%[![:space:]]*}"}"',
      '  case $rest in',
      "  '['*)",
      '    tasks=$(scan_tasks "${rest#?}")',
      '    case $tasks in',
      `    *'"status":"running"'*) printf '%s\\n' ${q(spec.blockBackground)}; exit 0 ;;`,
      '    esac',
      '    ;;',
      '  esac',
      'fi',
      `if [ ! -e ${q(spec.reminderFile)} ]; then`,
      `  : > ${q(spec.reminderFile)}`,
      `  printf '%s\\n' ${q(spec.blockNoDone)}`,
      '  exit 0',
      'fi',
      `printf '%s' "$payload" > ${q(spec.stopJson)}`,
      'exit 0',
      '',
    ].join('\n');
  }

  stopHookCommand(targetPath: string): string {
    return `bash ${this.quote(targetPath)}`;
  }

  readonly guideHookFile = 'looper-guide-hook';

  renderGuideHook(format: GuideHookFormat, files?: { guidance: string; notice: string }): string {
    const json = guideHookJson(format);
    return [
      '#!/usr/bin/env bash',
      '# generated by looper — guidance hook',
      'payload="$(cat)"',
      // A subagent's tool call: the guidance is for the session's own agent.
      `case "\${payload%%'"tool_input"'*}" in ${SUBAGENT_PATTERN}) exit 0 ;; esac`,
      ...this.takeGuidance(files ? this.quote(files.guidance) : `"$LOOPER_RUN_DIR/${GUIDANCE_FILE}"`, json),
      ...this.takeGuidance(files ? this.quote(files.notice) : `"$LOOPER_RUN_DIR/${NOTICE_FILE}"`, json),
      'exit 0',
      '',
    ].join('\n');
  }

  readonly guardHookFile = 'looper-subagent-guard';

  renderSubagentGuard(commands: readonly string[], message: string): string {
    return [
      '#!/usr/bin/env bash',
      '# generated by looper — subagent guard',
      'payload="$(cat)"',
      `case "\${payload%%'"tool_input"'*}" in ${SUBAGENT_PATTERN}) ;; *) exit 0 ;; esac`,
      `case "\${payload#*'"tool_input"'}" in ${commands.map((c) => `*${this.quote(c)}*`).join(' | ')})`,
      `  printf '%s\\n' ${this.quote(message)} >&2`,
      '  exit 2',
      '  ;;',
      'esac',
      'exit 0',
      '',
    ].join('\n');
  }

  codexHookCommand(targetPath: string): string | null {
    return /^[\w/.:@+-]+$/.test(targetPath) ? `bash ${targetPath}` : null;
  }

  readonly notifyHookFile = 'looper-notify';

  renderNotifyHook(stopJson: string): string {
    return [
      '#!/usr/bin/env bash',
      '# generated by looper — codex notify hook',
      `printf '%s' "$1" > ${this.quote(stopJson)}`,
      '',
    ].join('\n');
  }

  notifyCommand(targetPath: string): string[] {
    return ['bash', targetPath];
  }

  renderCodexHomeWrapper(command: string, codexHome: string): string {
    return [
      'real="${CODEX_HOME:-$HOME/.codex}"',
      `home=${this.quote(codexHome)}`,
      'mkdir -p "$home"',
      'if [ ! -f "$home/auth.json" ] && [ -f "$real/auth.json" ]; then',
      '  cp "$real/auth.json" "$home/auth.json" && cp "$real/auth.json" "$home/.auth-base"',
      '  chmod 600 "$home/auth.json" "$home/.auth-base" 2>/dev/null',
      'fi',
      `CODEX_HOME="$home" ${command}`,
      'code=$?',
      'if [ -f "$home/auth.json" ] && ! cmp -s "$home/auth.json" "$home/.auth-base"; then',
      '  if cmp -s "$real/auth.json" "$home/.auth-base"; then',
      '    cp "$home/auth.json" "$real/auth.json.looper" && chmod 600 "$real/auth.json.looper" && mv -f "$real/auth.json.looper" "$real/auth.json"',
      '  fi',
      '  cp "$home/auth.json" "$home/.auth-base"',
      'fi',
      'exit $code',
    ].join('\n');
  }

  renderBuilderHelpers(ops: Record<string, string>): Record<string, string> {
    const out: Record<string, string> = {};
    for (const [command, op] of Object.entries(ops)) {
      out[command] = [
        '#!/usr/bin/env bash',
        `# generated by looper — task builder helper (${command})`,
        'd="$LOOPER_BUILDER_DIR"',
        'rid="$(date +%s)-$$-$RANDOM"',
        'mkdir -p "$d/requests" "$d/responses"',
        // The op, the caller's folder (for relative paths), then one line per
        // argument; the rename makes the request appear whole.
        `{ printf '%s\\n' ${this.quote(op)} "$PWD"; for a in "$@"; do printf '%s\\n' "$a"; done; } > "$d/requests/$rid.tmp"`,
        'mv "$d/requests/$rid.tmp" "$d/requests/$rid.req"',
        'for _ in $(seq 1 7200); do',
        '  if [ -e "$d/responses/$rid.code" ]; then',
        '    cat "$d/responses/$rid.out" 2>/dev/null',
        '    code="$(cat "$d/responses/$rid.code")"',
        '    rm -f "$d/responses/$rid.out" "$d/responses/$rid.code"',
        '    exit "${code:-1}"',
        '  fi',
        '  sleep 0.5',
        'done',
        `echo 'looper: no answer from Looper (is the task builder window still open?)' >&2`,
        'exit 1',
        '',
      ].join('\n');
    }
    return out;
  }

  private wslPrefix(): string[] {
    if (this.ctx.host !== 'windows') return [];
    return this.distro ? ['wsl.exe', '-d', this.distro, '--'] : ['wsl.exe', '--'];
  }

  spawnSpec(launcherHostPath: string): SpawnSpec {
    const target = this.toTargetPath(launcherHostPath);
    const [cmd, ...flags] = this.shellParts;
    const sourceCmd = `source ${this.quote(target)}`;
    const full = [...this.wslPrefix(), cmd, ...flags, sourceCmd];
    return { command: full[0], args: full.slice(1) };
  }

  private runShell(script: string, timeoutMs: number): Promise<void> {
    const full = [...this.wslPrefix(), 'bash', '-c', script];
    return new Promise((resolve) => {
      try {
        execFile(full[0], full.slice(1), { timeout: timeoutMs, windowsHide: true }, () => resolve());
      } catch {
        resolve();
      }
    });
  }

  async killLeftovers(runId: string): Promise<void> {
    const script = this.ctx.host === 'mac' ? killScriptMac : killScript;
    await this.runShell(script(runId, 'TERM'), 10_000);
    await new Promise((r) => setTimeout(r, 1500));
    await this.runShell(script(runId, 'KILL'), 10_000);
  }
}
